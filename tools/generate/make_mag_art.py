"""Writes Explosive Reload's thrown magazines into
mods/firearms/players/hwp/firearms/projectiles/:

- mags.png (64x32; textures must be powers of two): 16x16 cells, row 0 the rifle's curved
  box magazine, row 1 the pistols' straight magazine (smaller). Columns are four tumble
  frames, the upright drawing turned 0/90/180/270 degrees, so the mag spins end over end
  in flight like vanilla's slingshot_rock. A red primer light on the baseplate blinks
  (lit in frames 0 and 2).
- mag_rifle.effect, mag_pistol.effect: the tumbling sprite (raised by the height param,
  as slingshot_rock.effect), fizzing sparks and a small red glow. The ground shadow is the
  unit's special/shadow.unit scene, not part of the effect. Params: angle, height.

    python tools/generate/make_mag_art.py [out_dir]
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from generate.make_bullet_art import h, draw, light, speckles  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "mods/firearms/players/hwp/firearms/projectiles"
TEX = "./mags.png"

# upright, feed lips at the top with a brass round showing; R is the primer light
RIFLE = [  # 10 x 13: a curved (banana) box magazine with two ribs
    ".oobbo....",
    ".oHBBo....",
    ".oHMMo....",
    ".oHMMmo...",
    "..oHMMo...",
    "..oHssmo..",
    "..oHMMmo..",
    "...oHMMo..",
    "...oHssmo.",
    "...oHMMmo.",
    "....oHMMo.",
    "...ommRmmo",
    "...ooooooo",
]
PISTOL = [  # 4 x 9 body, 5 wide baseplate
    ".obbo",
    ".oBBo",
    ".oHMo",
    ".oHMo",
    ".oHMo",
    ".oHMo",
    ".oHmo",
    "ooRmoo",
    "oooooo",
]
PAL = {"o": h("16161c"), "M": h("4a4f5c"), "H": h("8a91a3"), "m": h("2e313a"), "s": h("26282f"),
       "b": h("ffd27a"), "B": h("c8862e")}
LIT = {"R": h("ff4a3a")}
DIM = {"R": h("6a1414")}


def upright(rows, lit: bool) -> Image.Image:
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    w, hh = max(len(r) for r in rows), len(rows)
    draw(img, (16 - w) // 2, (16 - hh) // 2, rows, {**PAL, **(LIT if lit else DIM)})
    return img


def sheet() -> Image.Image:
    img = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    for r, rows in enumerate((RIFLE, PISTOL)):
        for f in range(4):
            cell = upright(rows, f % 2 == 0).rotate(-90 * f, resample=Image.NEAREST)
            img.alpha_composite(cell, (f * 16, r * 16))
    return img


def sprite(row: int, frame_ms: int) -> str:
    fr = "\n".join(f'\t\t<frame time="{frame_ms}">{f * 16} {row * 16} 16 16</frame>' for f in range(4))
    return f'''\t<sprite looping="true" origin="8 8" texture="{TEX}" material="system/default.mats:default"
\t\tpos-x="0"
\t\tpos-y="-height">
{fr}
\t</sprite>'''


def effect(comment: str, body: list[str]) -> str:
    return (f"<!-- {comment} Generated by tools/generate/make_mag_art.py; edit that, not this. -->\n"
            '<effect looping="true">\n'
            '\t<param name="angle" default="0" />\n'
            '\t<param name="height" default="0" />\n\n'
            + "\n\n".join(body) + "\n</effect>\n")


def effects() -> dict[str, str]:
    return {
        "mag_rifle.effect": effect("Explosive Reload: the thrown rifle magazine.", [
            sprite(0, 80), speckles("2.8;0.7;0.15;1", 14, 0, "rpick(150,350)"),
            light((1, 0.3, 0.2), 32, 0.3)]),
        "mag_pistol.effect": effect("Explosive Reload: a thrown pistol magazine (smaller).", [
            sprite(1, 70), speckles("2.8;0.7;0.15;1", 9, 0, "rpick(120,280)"),
            light((1, 0.3, 0.2), 24, 0.25)]),
    }


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    sheet().save(OUT / "mags.png")
    for name, text in effects().items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote mags.png and {len(effects())} effects in {OUT}")


if __name__ == "__main__":
    if len(sys.argv) > 1:          # an output dir, for previews
        OUT = Path(sys.argv[1])
    main()
