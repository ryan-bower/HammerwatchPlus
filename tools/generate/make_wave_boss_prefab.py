"""make_wave_boss_prefab.py - writes the wave arena's champion spawner prefab.

    python tools/generate/make_wave_boss_prefab.py            # (re)write the prefab
    python tools/generate/make_wave_boss_prefab.py --check    # exit 1 when the committed prefab is stale

The vanilla SurvivalMission module loads its "boss" parameter with Resources::GetPrefab
and fabricates it above the player once the bar is full (Missions/SurvivalMission.as:45,
126). The heaven trials pass a spawner prefab that runs the intro, spawns the boss and,
once it dies, the exit portal. A .unit path there leaves the prefab null and throws
"Null pointer access" when the bar fills, so the champion never came.

This copies the valor trial's spawner (prefabs/heaven/seg_heaven/boss_spawners/
heaven_warrior_spawner.pfb, read from .base/) with three changes:
  - SpawnUnit spawns actors/hwp/wave_boss.unit (the spirit warrior without the valor
    stat reward), so arena clears raise only the HWP arena rank;
  - the BossDefeated link no longer fires UnlockAchievement (boss_spirit_warrior) or
    SetCharacterFlag (boss_warrior): the DLC trial's achievement and flag are not ours
    to give; both scripts stay in place, disabled, so no link points at a missing id;
  - nothing else: intro effects, music, the enemy clear-out and the exit portal are the
    trial's own.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import hwr_archive as hwr  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / ".base/prefabs/heaven/seg_heaven/boss_spawners/heaven_warrior_spawner.pfb"
OUT = ROOT / "mods/wavemode/prefabs/hwp/wave_boss_spawner.pfb"
VANILLA_BOSS = "actors/bosses/spirits/warrior/boss_spirit_warrior.unit"
OUR_BOSS = "actors/hwp/wave_boss.unit"
DROPPED = ("UnlockAchievement", "SetCharacterFlag")

# worldscript row: [type, id, pos, enabled, triggerTimes, ..., params]
TYPE, ID, ENABLED = 0, 1, 3


def build() -> dict:
    pfb, _ = hwr.decode_svalue(SRC.read_bytes(), 0)
    scripts = pfb["scripts"]
    dropped = {row[ID] for row in scripts if row[TYPE] in DROPPED}
    if len(dropped) != len(DROPPED):
        raise SystemExit(f"expected one each of {DROPPED} in {SRC.name}, found ids {sorted(dropped)}")
    swapped = 0
    for row in scripts:
        if row[ID] in dropped:
            row[ENABLED] = False
        elif row[TYPE] == "SpawnUnit" and isinstance(row[-1], dict) and row[-1].get("UnitType") == VANILLA_BOSS:
            row[-1]["UnitType"] = OUR_BOSS
            swapped += 1
        elif row[TYPE] == "ScriptLink" and isinstance(row[-1], list):
            links = row[-1]
            row[-1] = [x for i in range(0, len(links), 2) if links[i] not in dropped for x in links[i:i + 2]]
    if swapped != 1:
        raise SystemExit(f"expected one SpawnUnit of {VANILLA_BOSS} in {SRC.name}, swapped {swapped}")
    return pfb


def render() -> bytes:
    head = "<!-- generated by tools/generate/make_wave_boss_prefab.py from vanilla's heaven_warrior_spawner.pfb; edit the generator, not this file -->\n"
    return (head + hwr.svalue_to_xml(build()) + "\n").encode("utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the committed prefab differs")
    args = ap.parse_args(argv)
    if not SRC.exists():
        print(f"{SRC.relative_to(ROOT).as_posix()} missing: extract the base game first (tools/extract_base.py)")
        return 1
    data = render()
    if args.check:
        if not OUT.exists() or OUT.read_bytes() != data:
            print(f"{OUT.relative_to(ROOT).as_posix()} is stale: run python tools/generate/make_wave_boss_prefab.py")
            return 1
        print("wave boss prefab up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(data)
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
