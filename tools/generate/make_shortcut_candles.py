"""Extend the Dark Citadel candle challenge.

python tools/generate/make_shortcut_candles.py [--check] [--source PATH]
The pristine .orig is retained for the override check and offline regeneration.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "mods/shortcuts/levels/shortcut_dark_citadel.lvl"
ORIGINAL = OUT.with_suffix(".lvl.orig")
CANDLE = "doodads/lamps/snake_pedestal_purple.unit"
DESTINATIONS = ("courts_1", "dark_halls_1", "dark_halls_boss")
POSITIONS = ((-80, 16), (16, -80), (112, 16))


def extend(root: ET.Element) -> ET.Element:
    root = deepcopy(root)
    scripts = root.find("array[@name='scripts']")
    units = root.find("dict[@name='units']")
    rows = {int(row[1].text): row for row in scripts}

    def params(id):
        return rows[id].find("dict")

    def links(id):
        return rows[id].findall("array")[-1]

    def append_ids(target, *ids):
        for id in ids:
            ET.SubElement(target, "int").text = str(id)

    def clone(template, id):
        row = deepcopy(rows[template])
        row[1].text = str(id)
        scripts.append(row)
        rows[id] = row
        return row

    def replace_ids(array, *ids):
        array[:] = []
        append_ids(array, *ids)

    if (rows[222][0].text != "CheckVariables"
            or params(222).find("int[@name='Value']").text != "3"
            or params(277).find("string[@name='LevelID']").text != "barracks_1"):
        raise ValueError("unsupported Dark Citadel shortcut graph")

    pedestals = units.find(f"array[@name='{CANDLE}']")
    circles = units.find("array[@name=':Physics_Circle']")
    pedestal = next(row for row in pedestals if row[1].text == "38")
    circle = next(row for row in circles if row[1].text == "20")

    for i, position in enumerate(POSITIONS):
        candle_id, area_id = 1000 + 2 * i, 1001 + 2 * i
        for template, parent, id in ((pedestal, pedestals, candle_id), (circle, circles, area_id)):
            row = deepcopy(template)
            row[0].text = " ".join(map(str, position))
            row[1].text = str(id)
            parent.append(row)

        # Each candle uses vanilla's toggle, four-wave spawn link and completion counter.
        mapping = {old: 1100 + i * 10 + n for n, old in enumerate((232, 233, 231, 234, 230, 236, 303))}
        for old, new in mapping.items():
            row = clone(old, new)
            for element in row.iter("int"):
                if element is row[1]:
                    continue
                value = int(element.text)
                if value in mapping:
                    element.text = str(mapping[value])
                elif value == 38:
                    element.text = str(candle_id)
                elif value == 20:
                    element.text = str(area_id)
        # Extra candles increase the skip and the fight, not the existing loot payout.
        replace_ids(links(mapping[236]), 266, 0)
        append_ids(links(328), mapping[303], 0)
        append_ids(links(291), mapping[236], 0)
        append_ids(params(320).find("array[@name='Scripts']"), mapping[232])

    # Keep vanilla's shortcut-3 gate, separately per NG+, for the added candles.
    clone(349, 1200)
    replace_ids(params(1200).find("array[@name='Units']"), 1000, 1002, 1004)
    replace_ids(links(1200), 1201, 0)
    clone(320, 1201)
    replace_ids(params(1201).find("array[@name='Scripts']"), 1100, 1110, 1120)
    append_ids(links(348), 1200, 0)

    # Exactly one exit can be enabled on completion, using the highest lit threshold.
    replace_ids(params(222).find("array[@name='OnTrue']"), 1300)
    for i, destination in enumerate(DESTINATIONS):
        check, toggle, exit = 1300 + i * 3, 1301 + i * 3, 1302 + i * 3
        row = clone(222, check)
        # Only the original completion check spawns the portal (script 283).
        for output in row.findall("array"):
            row.remove(output)
        params(check).find("int[@name='Value']").text = str(4 + i)
        replace_ids(params(check).find("array[@name='OnTrue']"), check + 3 if i < 2 else toggle)
        replace_ids(params(check).find("array[@name='OnFalse']"), 269 if i == 0 else toggle - 3)
        clone(269, toggle)
        replace_ids(params(toggle).find("array[@name='Scripts']"), exit)
        clone(277, exit)
        params(exit).find("string[@name='LevelID']").text = destination
    return root


def render(source: Path) -> bytes:
    root = extend(ET.fromstring(source.read_bytes()))
    text = source.read_text(encoding="utf-8-sig")
    header = re.search(r"<!--\s*hwp-level-header\s+[0-9a-fA-F]{16}\s*-->", text)
    prefix = header.group(0) + "\n" if header else ""
    ET.indent(root, space="\t")
    return (prefix + "<!-- Generated by tools/generate/make_shortcut_candles.py. -->\n"
            + ET.tostring(root, encoding="unicode") + "\n").encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ORIGINAL)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = render(args.source)
    if args.check:
        if not OUT.exists() or OUT.read_bytes() != data:
            print("shortcut candles are stale; run tools/generate/make_shortcut_candles.py")
            return 1
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        if args.source != ORIGINAL:
            if ORIGINAL.exists() and ORIGINAL.read_bytes() != args.source.read_bytes():
                raise ValueError("refusing to replace a different pristine shortcut level")
            ORIGINAL.write_bytes(args.source.read_bytes())
        OUT.write_bytes(data)
    print("shortcut candles up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
