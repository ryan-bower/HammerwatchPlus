"""Writes mods/farming/doodads/hwp/wild/<seed>.unit: the in-run wild crop
plots (one ripe plot per floor, HWP::Farming::SetupRun). Each is a soil patch
with three of that crop's ready sprites (copied from doodads/hwp/crops/) and
the crop icon of mods/hwplib/gui/hwp/map_icons.png on the minimap.

    python tools/make_wild_plots.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FARM = ROOT / "mods" / "farming" / "doodads" / "hwp"
SEEDS = ["cabbage", "carrot", "onion", "potato", "wheat",
         "lucky_leaf", "ember_kush", "saints_sage"]
SPOTS = [(-9, 0), (9, 1), (0, 4)]

UNIT = """<!-- In-run wild {seed} plot (generated by tools/make_wild_plots.py). The host spawns one
     per floor beside a pot, crate or chest (HWP::Farming::SetupRun); it is netsynced, but
     every player harvests it once for themselves (HWPWildPlot, local yield, doubled seed
     chance) and then it disappears for them. Nothing can be planted on it. -->
<unit slot="doodad">
	<behavior class="HWPLocalNPC">
		<int name="hp">100000</int>
		<bool name="targetable">false</bool>
		<int name="experience-reward">0</int>
		<int name="aggro-range">150</int>
		<int name="max-range">300</int>
		<bool name="must-see-target">true</bool>
		<bool name="no-buffs">true</bool>
		<bool name="hide-health">true</bool>
		<bool name="hide-damage-numbers">true</bool>
		<bool name="hide-damage-flash">true</bool>
		<vec2 name="icon-offset">0 -22</vec2>
		<vec3 name="dialog-offset">0 -20 0</vec3>
		<array name="tags"></array>
		<dict name="interact">
			<string name="class">HWPWildPlot</string>
			<string name="seed">{seed}</string>
			<int name="break-distance">50</int>
			<array name="icon"><s>doodads/hwp/farm.png</s><i>100</i><vec4>32 0 16 16</vec4></array>
		</dict>
		<dict name="movement">
			<string name="class">EmptyMovement</string>
		</dict>
		<array name="skills" />
	</behavior>

	<scenes default="plot">
		<scene name="plot">
			<minimap_sprite texture="gui/hwp/map_icons.png" frame="24 0 9 11" origin="4 5" layer="400" />
			<collision>
				<rect sensor="true">-18 -14 36 28</rect>
			</collision>
			<sprite origin="16 10" texture="doodads/hwp/farm.png" material="system/default.mats:floor">
				<frame>0 0 32 20</frame>
			</sprite>
{crops}		</scene>
	</scenes>
</unit>
"""


def main():
    out = FARM / "wild"
    out.mkdir(parents=True, exist_ok=True)
    for seed in SEEDS:
        src = (FARM / "crops" / f"{seed}.unit").read_text(encoding="utf-8")
        m = re.search(r'<sprite origin="([^"]+)" texture="([^"]+)" material="([^"]+)">\s*<frame>([^<]+)</frame>', src)
        assert m, seed
        origin, texture, material, frame = m.groups()
        crops = ""
        ox, oy = (int(v) for v in origin.split())
        # back to front by their feet: without a ulayer of their own, the three overlapping
        # sprites of one unit swapped places from frame to frame (an orange Ember Kush flickered)
        for layer, (dx, dy) in enumerate(sorted(SPOTS, key=lambda s: s[1]), 1):
            # sprites have no offset attribute: shift the origin instead
            crops += (f'\t\t\t<sprite origin="{ox - dx} {oy - dy}" ulayer="{layer}" texture="{texture}" material="{material}">\n'
                      f'\t\t\t\t<frame>{frame}</frame>\n\t\t\t</sprite>\n')
        (out / f"{seed}.unit").write_text(UNIT.format(seed=seed, crops=crops), encoding="utf-8", newline="\n")
    print("wrote", len(SEEDS), "wild plots to", out)


if __name__ == "__main__":
    main()
