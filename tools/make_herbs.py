"""The Holy Herb strains of mods/farming, from one table (STRAINS). A strain used to be copied
by hand into seven files and three sprite sheets indexed by seed order (issue #15); this
writes them all:

- tweak/hwp/buffs_herbs.sval: each strain's hwp_herb mission buff (its modifiers)
- tweak/hwp/equipment_joints.sval: the joint items, 5 stages x 2 hands (the %block lines)
- res/language/english/hwp_farming_herbs.lang: names, buff text, joint names
- scripts/HWP/Farming/Herbs.as: DefineHerbs(), the AddSeed lines (seed price, ware price)
- doodads/hwp/crops/<strain>.unit: the ripe plant on a farm plot
- the art, recoloured from Lucky Leaf's (a light / mid / dark ramp; the stem stays):
  doodads/hwp/farm.png (the plant, 16 px at y 24, and the buff icon, 24 px at y 40),
  gui/hwp_seeds.png (a 13 px packet) and gui/hwp_harvest.png (a 16 px bud), both indexed
  by DefineSeeds order: the food crops (FOOD), then the strains.

- doodads/hwp/wild/<strain>.unit: its in-run wild plot (tools/make_wild_plots.py, whose
  SEEDS come from here) The farming module's self-check counts what loaded (`self-check done: <seeds>
seeds, <strains> herb buffs, <strains x 10> joint items`).

    python tools/make_herbs.py           # write
    python tools/make_herbs.py --check   # exit 1 if a file is not what the table makes
"""
import argparse
import io
import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FARM = ROOT / "mods" / "farming"

# DefineSeeds' food crops, in order: cells 0-4 of the seed and harvest sheets
FOOD = ["cabbage", "carrot", "onion", "potato", "wheat"]

LEAF_TEMPLATE = ((150, 220, 120), (64, 168, 72), (28, 96, 40))  # Lucky Leaf: light, mid, dark
JOINT_STAGES = 5


@dataclass
class Strain:
    id: str
    name: str
    desc: str          # the buff's text (lang)
    price: int         # a seed at the farmer
    sell: int          # a harvested bud, as a ware
    palette: tuple     # light, mid, dark (the leaf); the seed packet's plant is mid
    modifiers: str     # the mission buff's <dict>s (MissionBuff modifiers)
    packet: tuple = None  # the seed packet's plant colour, when not the mid one


STRAINS = [
    Strain("lucky_leaf", "Lucky Leaf",
           "The Gambler redraws a losing dealer card once (25 %) and gold find +5 %.", 150, 120,
           LEAF_TEMPLATE,
           '<dict>\n\t\t\t\t<string name="class">Modifiers::MaterialGain</string>\n'
           '\t\t\t\t<float name="gold-mul">1.05</float>\n\t\t\t</dict>'),
    Strain("ember_kush", "Ember Kush", "+20 % fire damage.", 200, 160,
           ((255, 170, 90), (204, 90, 40), (120, 40, 20)),
           '<dict>\n\t\t\t\t<string name="class">Modifiers::DamageMulAdd</string>\n'
           '\t\t\t\t<float name="fire">0.2</float>\n\t\t\t</dict>'),
    Strain("saints_sage", "Saint's Sage", "+1.0 health and +0.5 mana regeneration.", 200, 160,
           ((232, 248, 255), (140, 196, 228), (60, 100, 140)),
           '<dict>\n\t\t\t\t<string name="class">Modifiers::AttribAdd</string>\n'
           '\t\t\t\t<float name="health-regen">1.0</float>\n'
           '\t\t\t\t<float name="mana-regen">0.5</float>\n\t\t\t</dict>',
           packet=(60, 100, 140)),
    # issue #15: lightning's counterpart of Ember Kush, in the game's lightning violet
    # (tweak/player_colors.sval lightning_gem: e69eff, c318e7 / 9d18e7)
    Strain("lightning_kush", "Lightning Kush", "+20 % lightning damage.", 200, 160,
           ((230, 158, 255), (160, 64, 224), (88, 24, 144)),
           '<dict>\n\t\t\t\t<string name="class">Modifiers::DamageMulAdd</string>\n'
           '\t\t\t\t<float name="lightning">0.2</float>\n\t\t\t</dict>'),
]

# farm.png has room for four strains (y 24 and y 40 hold the plants and the buff icons;
# the watering cans start at x 64 / x 96 to their right)
FARM_SLOTS = 4


def strain(id_):
    return next(s for s in STRAINS if s.id == id_)


def seed_ids():
    return FOOD + [s.id for s in STRAINS]


# ---- text files ---------------------------------------------------------------------

GEN = "Generated by tools/make_herbs.py (STRAINS); do not edit."


def buffs_sval():
    out = [f"""<!-- {GEN}
     A puff of a Holy Herb joint sets one of these as the player's "hwp_herb"
     mission buff (PlayerRecord.SetMissionBuff); the farming module keeps it for
     10 floors (FarmingModule.as KeepHerb). Lucky Leaf's gambling effect lives in
     the Gambler. -->
<loader>MissionBuff::LoadMultiple</loader>
<array>
"""]
    for i, s in enumerate(STRAINS):
        out.append(f"""\t<dict>
\t\t<string name="id">hwp_herb_{s.id}</string>
\t\t<string name="name">.hwp.farming.seed.{s.id}</string>
\t\t<string name="description">.hwp.farming.herb.{s.id}.desc</string>
\t\t<string name="set">hwp_herb</string>
\t\t<int name="cost-gold">0</int>
\t\t<bool name="blueprint">false</bool>
\t\t<array name="icon"><s>doodads/hwp/farm.png</s><i>100</i><vec4>{24 * i} 40 24 24</vec4></array>
\t\t<string name="quality">uncommon</string>
\t\t<array name="modifiers">
\t\t\t{s.modifiers}
\t\t</array>
\t</dict>
""")
    out.append("</array>\n")
    return "".join(out)


def joints_sval(current: str):
    """The %block lines at the end of equipment_joints.sval (the defblocks stay as written)."""
    lines = []
    for block in ("Joint", "JointMH"):
        for s in STRAINS:
            for n in range(JOINT_STAGES, 0, -1):
                lines.append(f"\t%block {block} {s.id} {n} {(JOINT_STAGES - n) * 24}")
            lines.append("")
    blocks = "\n".join(lines)
    m = re.search(r"%endblock\n(?:(?!%endblock).)*?\n(\t%block Joint .*?)</array>", current, re.S)
    assert m, "equipment_joints.sval: no %block section before </array>"
    marker = f"\t<!-- the strains: {GEN} -->\n"
    start = m.start(1)
    head = current[:start]
    if head.endswith(marker):
        head = head[:-len(marker)]
    return head + marker + blocks + "</array>" + current[m.end():]


def herbs_lang():
    out = [f'<!-- {GEN} -->\n<lang name="English" official="false">\n']
    for s in STRAINS:
        name = s.name.replace("&", "&amp;")
        out.append(f'\t<string name="hwp.farming.seed.{s.id}">{name}</string>\n')
        out.append(f'\t<string name="hwp.farming.herb.{s.id}.desc">{s.desc}</string>\n')
        for n in range(JOINT_STAGES, 0, -1):
            out.append(f'\t<string name="hwp.farming.joint.{s.id}.{n}">{name} Joint ({n}/{JOINT_STAGES})</string>\n')
    out.append("</lang>\n")
    return "".join(out)


def herbs_as():
    adds = "".join(f'\t\t\tAddSeed("{s.id}", {s.price}, true, 4, {s.sell});\n' for s in STRAINS)
    return f"""// {GEN}
// The Holy Herb strains, after the food crops (DefineSeeds): their order is the seed and
// harvest sheets' (gui/hwp_seeds.png, gui/hwp_harvest.png).
namespace HWP
{{
	namespace Farming
	{{
		void DefineHerbs()
		{{
{adds}\t\t}}
	}}
}}
"""


def crop_unit(i, s):
    return f"""<!-- {s.name} (ready) (purely visual, spawned locally by HWP::Farming::RefreshVisuals). {GEN} -->
<unit slot="doodad" netsync="none">
	<scenes default="plant">
		<scene name="plant">
			<sprite origin="8 15" texture="doodads/hwp/farm.png" material="system/default.mats:proj-prop">
				<frame>{16 * i} 24 16 16</frame>
			</sprite>
		</scene>
	</scenes>
</unit>
"""


# ---- art ----------------------------------------------------------------------------

def recolour(cell: Image.Image, s: Strain, packet=False):
    """Lucky Leaf's cell in the strain's colours: each template ramp colour to the strain's
    (a seed packet's plant is one colour, mid in the template)."""
    out = cell.copy()
    px = out.load()
    src = {c: s.palette[k] for k, c in enumerate(LEAF_TEMPLATE)}
    if packet:
        src = {LEAF_TEMPLATE[1]: s.packet or s.palette[1]}
    for y in range(out.height):
        for x in range(out.width):
            r, g, b, a = px[x, y]
            if a and (r, g, b) in src:
                px[x, y] = (*src[(r, g, b)], a)
    return out


def sheet(path: Path, cell_w: int, cell_h: int, index0: int, packet=False, min_w=0):
    """The sheet with every strain's cell drawn from the template's (cell index0 + 0)."""
    im = Image.open(path).convert("RGBA")
    need = (index0 + len(STRAINS)) * cell_w
    w = im.width
    while w < max(need, min_w):
        w *= 2  # GUI textures must stay power-of-two sized (README, mod-all)
    if w != im.width:
        grown = Image.new("RGBA", (w, im.height), (0, 0, 0, 0))
        grown.paste(im, (0, 0))
        im = grown
    template = im.crop((index0 * cell_w, 0, index0 * cell_w + cell_w, cell_h))
    for i, s in enumerate(STRAINS):
        x = (index0 + i) * cell_w
        im.paste(recolour(template, s, packet), (x, 0))
    return im


def farm_png():
    path = FARM / "doodads" / "hwp" / "farm.png"
    assert len(STRAINS) <= FARM_SLOTS, f"farm.png holds {FARM_SLOTS} strains: lay out room for more first"
    im = Image.open(path).convert("RGBA")
    plant = im.crop((0, 24, 16, 40))
    icon = im.crop((0, 40, 24, 64))
    for i, s in enumerate(STRAINS):
        im.paste(recolour(plant, s), (16 * i, 24))
        im.paste(recolour(icon, s), (24 * i, 40))
    return im


def png_bytes(im):
    b = io.BytesIO()
    im.save(b, "PNG", optimize=True)
    return b.getvalue()


def same_pixels(path: Path, im: Image.Image):
    if not path.exists():
        return False
    old = Image.open(path).convert("RGBA")
    return old.size == im.size and old.tobytes() == im.tobytes()


# ---- main ---------------------------------------------------------------------------

def outputs():
    """{path: str | Image}"""
    joints = FARM / "tweak" / "hwp" / "equipment_joints.sval"
    out = {
        FARM / "tweak" / "hwp" / "buffs_herbs.sval": buffs_sval(),
        joints: joints_sval(joints.read_text(encoding="utf-8")),
        FARM / "res" / "language" / "english" / "hwp_farming_herbs.lang": herbs_lang(),
        FARM / "scripts" / "HWP" / "Farming" / "Herbs.as": herbs_as(),
        FARM / "doodads" / "hwp" / "farm.png": farm_png(),
        FARM / "gui" / "hwp_seeds.png": sheet(FARM / "gui" / "hwp_seeds.png", 13, 16, len(FOOD), packet=True),
        FARM / "gui" / "hwp_harvest.png": sheet(FARM / "gui" / "hwp_harvest.png", 16, 16, len(FOOD)),
    }
    import make_wild_plots
    for i, s in enumerate(STRAINS):
        unit = crop_unit(i, s)
        out[FARM / "doodads" / "hwp" / "crops" / f"{s.id}.unit"] = unit
        out[FARM / "doodads" / "hwp" / "wild" / f"{s.id}.unit"] = make_wild_plots.wild_unit(s.id, unit)
    return out


def stale():
    bad = []
    for path, want in outputs().items():
        if isinstance(want, Image.Image):
            if not same_pixels(path, want):
                bad.append(path)
        elif not path.exists() or path.read_text(encoding="utf-8") != want:
            bad.append(path)
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a file is not what STRAINS makes")
    args = ap.parse_args(argv)
    if args.check:
        bad = stale()
        for p in bad:
            print("make_herbs: stale", p.relative_to(ROOT))
        print("make_herbs:", "OK" if not bad else f"{len(bad)} stale (python tools/make_herbs.py)")
        return 1 if bad else 0
    for path, want in outputs().items():
        if isinstance(want, Image.Image):
            if not same_pixels(path, want):
                path.write_bytes(png_bytes(want))
                print("wrote", path.relative_to(ROOT))
        elif not path.exists() or path.read_text(encoding="utf-8") != want:
            path.write_text(want, encoding="utf-8", newline="\n")
            print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
