"""Writes mods/specs/players/hwp/specs/class_specs.sval: the eight 4th specializations as
subclasses of their vanilla class (a subclass is a PlayerClass with a parent; the trainer and
the subclass picker list any number of them per class).

python tools/make_specs_classes.py [--check]

A subclass carries the full stat block, so each one gets a copy of its vanilla class's
SharedStats block (gamecode/sdk/hoh2/players/<cls>/class_<cls>.sval), and its skills list is
the vanilla base kit (from the vanilla class entry) plus the spec's active and passive. A spec
that changes a vanilla skill lists its own copy instead (COPIES: the vanilla file with its effect
classes swapped, the same ids and orbs, written next to the spec's skills), so no other
character of the class is touched. Rerun after a game patch; --check exits 1 when a file is
stale."""
import re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
VANILLA = REPO / "gamecode/sdk/hoh2/players"
OUT = REPO / "mods/specs/players/hwp/specs/class_specs.sval"

# class, subclass id, spec folder, active, passive, icon cell in the specs sheet
SPECS = [
    ("ranger", "hwp_ranger_stormbringer", "stormbringer", "electric_circuit", "gathering_winds", 0),
    ("wizard", "hwp_wizard_invocation", "invocation", "tempest_torrent", "static_charge", 1),
    ("sorcerer", "hwp_sorcerer_arcane", "arcane", "blink", "living_mana", 2),
    ("rogue", "hwp_rogue_winddancer", "winddancer", "protective_gale", "second_wind", 3),
    ("warrior", "hwp_warrior_bannerlord", "bannerlord", "battlefield_standard", "righteous_crusade", 4),
    ("warlock", "hwp_warlock_branding", "branding", "pyrebrand", "essence_extraction", 5),
    ("priest", "hwp_priest_forgemaster", "forgemaster", "necrotic_resurrection", "call_of_heresy", 6),
    ("paladin", "hwp_paladin_generosity", "generosity", "pelors_fury", "pelors_blessing", 7),
]

# spec folder -> [(vanilla skill, [(vanilla text, replacement)])]: Generosity's Lay on Hands heals
# through HWPGenHeal / HWPGenHPHeal (Pelor's Blessing scales them and counts who they heal) and its
# Conviction gives mana through HWPGenConvictionMana (mods/specs/scripts/HWP/Specs/Generosity.as)
COPIES = {
    "generosity": [
        ("paladin/skills/pal_lay_on_hands.sval",
         [('<string name="class">Heal</string>', '<string name="class">HWPGenHeal</string>'),
          ('<string name="class">HPBasedHeal</string>', '<string name="class">HWPGenHPHeal</string>')]),
        ("paladin/skills/pal_conviction.sval",
         [('<string name="class">GivePercentageMana</string>', '<string name="class">HWPGenConvictionMana</string>')]),
    ],
}


def vanilla(cls):
    text = (VANILLA / cls / f"class_{cls}.sval").read_text(encoding="utf-8")
    stats = re.search(r"%defblock SharedStats\n(.*?)%endblock", text, re.S).group(1)
    entry = re.search(r'<string name="id">' + cls + r'</string>.*?<array name="skills">(.*?)</array>', text, re.S).group(1)
    skills = [s for s in re.findall(r"^\s*<string>([^<]+)</string>", entry, re.M)]
    return stats.rstrip(), skills


def copy_path(folder, src):
    return f"players/hwp/specs/{folder}/{src.rsplit('/', 1)[1]}"


def copies():
    """{repo path: text} of every spec's copy of a vanilla skill."""
    ret = {}
    for folder, items in COPIES.items():
        for src, swaps in items:
            text = (VANILLA / src).read_text(encoding="utf-8")
            for old, new in swaps:
                assert old in text, (src, old)
                text = text.replace(old, new)
            head, nl, rest = text.partition("\n")
            assert head.startswith("%include"), src
            names = ", ".join(re.search(r">([^<]+)<", new).group(1) for _, new in swaps)
            note = (f"<!-- Generated by tools/make_specs_classes.py: players/{src} for the {folder} spec, with\n"
                    f"     its effect classes swapped ({names}). -->")
            ret["mods/specs/" + copy_path(folder, src)] = head + nl + note + nl + rest
    return ret


def build():
    out = ['<loader order="1">PlayerClass::LoadMultiple</loader>', "",
           "<!-- Generated by tools/make_specs_classes.py: the eight 4th specializations, each a",
           "     subclass of its vanilla class. Stats are copies of the parent's SharedStats block. -->",
           "<array>"]
    for cls, sid, folder, active, passive, row in SPECS:
        stats, skills = vanilla(cls)
        swapped = {"players/" + src: copy_path(folder, src) for src, _ in COPIES.get(folder, [])}
        skills = [swapped.get(s, s) for s in skills]
        out += ["", "\t<dict>",
                f'\t\t<string name="parent">{cls}</string>',
                f'\t\t<string name="id">{sid}</string>',
                f'\t\t<string name="name">.hwp.specs.{folder}.name</string>',
                f'\t\t<string name="description">subclass of {cls}</string>', "",
                f'\t\t<array name="icon"><s>players/hwp/specs/icons.png</s><i>100</i><vec4>0 {row * 24} 24 24</vec4></array>', "",
                '\t\t<array name="skills">']
        out += [f"\t\t\t<string>{s}</string>" for s in skills]
        out += [f"\t\t\t<string>players/hwp/specs/{folder}/{active}.sval</string>",
                f"\t\t\t<string>players/hwp/specs/{folder}/{passive}.sval</string>",
                "\t\t</array>", ""]
        out += ["\t" + line if line.strip() else "" for line in stats.splitlines()]
        out += ["\t</dict>"]
    out += ["</array>", ""]
    return "\n".join(out)


def main():
    files = {OUT: build(), **{REPO / p: body for p, body in copies().items()}}
    if "--check" in sys.argv:
        stale = [p for p, body in files.items() if not p.exists() or p.read_text(encoding="utf-8") != body]
        for p in stale:
            print("stale:", p.relative_to(REPO))
        if stale:
            sys.exit(1)
        return
    for p, body in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8", newline="\n")
        print("wrote", p.relative_to(REPO))


if __name__ == "__main__":
    main()
