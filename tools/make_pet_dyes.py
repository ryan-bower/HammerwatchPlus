"""Two-section pet dyes (HWP::PetDye): writes, for every pet in PETS, dye-ready
copies of its sprite sheets and units, plus the section names the tailor shows.

The engine's multicolour sprite shader (system/shaders/sprite_mcol_glsl.fs)
draws .tif textures only (a .png is drawn as it is, whatever SetMultiColor
says). Unpacked mods load real TIFFs; a packed .tif is raw RGBA behind a
12-byte header: u32 width, u32 height, u32 colour channels (vanilla example:
actors/aberrations/eyes/eye/eye_idle.tif, 2 channels; hwr_archive.py
tiff_to_texture converts when packing). The shader reads every texel with alpha >= 0.5 as
an index: green = colour channel
(0-15), red = shade (0 = the dye's dark colour, 0.5 = mid, 1 = bright). Texels
with alpha < 0.5 are drawn as they are, at twice their alpha. So each variant
stores the dyed section's pixels as (shade, channel, 0, 255) and every other
pixel at half alpha, which leaves them exactly as before.

Three variants per pet, so an undyed section always keeps its own colours:
    _p   primary section dyed (channel 0)
    _s   secondary section dyed (channel 1)
    _ps  both

The units name our behaviour classes (the pets module.json "class_swaps";
the engine ignores info.xml classmaps, see tools/class_units.py, which writes
the vanilla pet units' copies): the variants get them here, and the HoH1
imports (players/pets/hwp/*.unit) are rewritten in place.

Outputs (gitignored, made from your own HoH2 install (gamecode/sdk/hoh2/, tools/bootstrap.py)
and HoH1 import (tools/import_hoh1.py pets)):
    mods/pets/players/pets/hwp_dye/<texture>_<v>.tif, <pet id>_<v>.unit
        the vanilla pets' copies, made from the HoH2 base on every machine, so they ship
        (the pets .gitignore lists the folder in a "generated from the HoH2 base" block)
    mods/pets/players/pets/hwp/dye/<texture>_<v>.tif, <pet id>_<v>.unit
        the HoH1 pets' copies: `local` in the pets module.json like the rest of
        players/pets/hwp/, never released (until 2026-10-28 the vanilla copies sat here too,
        so release builds dropped them and two-section dyes did nothing on vanilla pets)
    mods/pets/scripts/HWP/Pets/PetDyeParts.as   (committed: ids and section names)
    mods/pets/players/pets/hwp_dye/.hwp-generated.json   (this script's hash and every source's
        hash, so `python -m gamelab doctor` can tell a stale or partial set; dotfiles never pack)

    python tools/make_pet_dyes.py            # pets whose sources exist
    python tools/make_pet_dyes.py --check    # also print each section's pixel counts
    python tools/make_pet_dyes.py --verify   # exit 1 if the copies are missing or stale, write nothing
"""
