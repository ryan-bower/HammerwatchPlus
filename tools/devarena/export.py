"""Export one Dev Arena tuner version to the vanilla-tuning mod (docs/devarena/SPEC.md,
"Decided during build" 5).

A version is the full list of edits on top of vanilla, so exporting it is copying its rows:
mods/vanilla-tuning/tweak/hwp/vanilla_tuning.sval. The mod replays them on the skill defs at
runtime (mods/vanilla-tuning/scripts/HWP/VanillaTuning/Apply.as) with a copy of the tuner's
Patch.as, so it shadows no base file. Patching the datatables JSON is not an option:
gamecode/datatables/*.sval.json is lossy (vectors dump as float arrays, the preprocessor's
includes are already expanded).

    python tools/devarena/export.py [--version N|live|a|b] [--from SVAL | --log LOG] [--note TEXT]
    python tools/devarena/export.py --patch      # regenerate the mod's Patch.as only
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from tools.devarena import overrides  # noqa: E402

REPO = overrides.REPO
MOD = REPO / "mods" / "vanilla-tuning"
OUT = MOD / "tweak" / "hwp" / "vanilla_tuning.sval"
PATCH_SRC = REPO / "mods" / "devarena" / "scripts" / "HWP" / "DevArena" / "Patch.as"
PATCH_DST = MOD / "scripts" / "HWP" / "VanillaTuning" / "Patch.as"
HEADER = ("<!-- Vanilla Tuning edits, exported from the Dev Arena tuner by tools/devarena/export.py.\n"
          "     Rows: [skill id, level index (0 = base, k = upgrades[k-1]), path, value]. -->\n")
GENERATED = "// GENERATED by tools/devarena/export.py from mods/devarena/scripts/HWP/DevArena/Patch.as; do not edit.\n"


def patch_text() -> str:
    src = PATCH_SRC.read_text(encoding="utf-8")
    if "namespace DevArena" not in src:
        raise ValueError(f"{PATCH_SRC} has no 'namespace DevArena'")
    return GENERATED + src.replace("namespace DevArena", "namespace VanillaTuning").replace("Dev Arena:", "Vanilla Tuning (from the Dev Arena):", 1)


def pick(state: dict, which: str) -> int:
    n = len(state["versions"])
    v = {"live": state["live"], "a": state["a"], "b": state["b"]}.get(which.lower())
    if v is None:
        v = int(which.lstrip("v"))
    if not 0 <= v <= n:
        raise ValueError(f"version {which!r} -> {v} is not in 0..{n}")
    return v


def export_doc(state: dict, version: int, note: str | None = None) -> dict:
    edits = [] if version == 0 else state["versions"][version - 1]["edits"]
    composed = sorted({e[0] for e in edits if str(e[2]).startswith("@")})
    if composed:
        # the mod replays rows with Patch.as, which has no composer; a composed skill ships in a
        # spec mod instead (tools/devarena/clone_spec.py)
        raise ValueError(f"v{version} composes {', '.join(composed)}: use tools/devarena/clone_spec.py, not export")
    vnote = "vanilla" if version == 0 else state["versions"][version - 1].get("note", "")
    return {"schema": 1, "version": version, "note": note or f"v{version}: {vnote}",
            "edits": [list(e) for e in edits]}


def to_sval(doc: dict) -> str:
    return HEADER + overrides.hwr_archive.svalue_to_xml(doc) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", default="live", help="N, live, a or b (default live)")
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--from", dest="sval", help="an override .sval (default the devarena mod's)")
    src.add_argument("--log", help="a game log: use its last override line")
    ap.add_argument("--note")
    ap.add_argument("--out", help=f"default {OUT.relative_to(REPO)}")
    ap.add_argument("--patch", action="store_true", help="only regenerate the mod's Patch.as")
    a = ap.parse_args(argv)

    PATCH_DST.parent.mkdir(parents=True, exist_ok=True)
    text = patch_text()
    if not PATCH_DST.exists() or PATCH_DST.read_text(encoding="utf-8") != text:
        PATCH_DST.write_text(text, encoding="utf-8")
        print(f"wrote {PATCH_DST.relative_to(REPO)}")
    if a.patch:
        return 0

    if a.log:
        state = overrides.last_in(Path(a.log).read_text(encoding="utf-8", errors="replace"))
        if state is None:
            print(f"no override line in {a.log}")
            return 1
    else:
        state = overrides.from_sval(Path(a.sval or overrides.SVAL).read_text(encoding="utf-8"))
    v = pick(state, a.version)
    try:
        doc = export_doc(state, v, a.note)
    except ValueError as e:
        print(f"refused: {e}")
        return 1
    out = Path(a.out) if a.out else OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(to_sval(doc), encoding="utf-8")
    print(f"wrote {out}: {doc['note']}, {len(doc['edits'])} edits")
    return 0


if __name__ == "__main__":
    sys.exit(main())
