"""Bake one Dev Arena tuner version into the mod skill files it tuned.

The tuner (mods/devarena, Tune tab) edits the skills of whatever class the player is playing,
the mods' own specs and classes included. A version is the list of edits
[skill id, level index (0 = the base "skill" dict, k = upgrades[k-1]), path, value]. Each edit
is written into the .sval under mods/ whose top-level id is the skill id
(clone_spec.patch_leaf), and the skill's description-params are made to show the new numbers
(clone_spec.fix_tooltips). Nothing is written unless every edit applies. Refused:
- a vanilla skill: HammerwatchPlus does not rebalance vanilla classes;
- a composed skill (clone_spec.py ships those in a new spec mod);
- a modifier sub-skill (its dict is nested in its parent's file: edit that by hand);
- a leaf the file does not spell out at that level (not guessed).

    python tools/devarena/export.py [--version N|live|a|b] [--from SVAL | --log LOG] [--dry-run]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from tools.devarena import clone_spec, overrides  # noqa: E402

REPO = overrides.REPO
MODS = REPO / "mods"
SKIP = ("devarena", "gamelab-")
# the header of a vanilla skill copied by tools/make_specs_classes.py (class_specs.sval's own differs)
GENERATED = "Generated by tools/make_specs_classes.py: players/"
TOP_ID = re.compile(r'^\t<string name="id">([^<]+)</string>', re.M)


def pick(state: dict, which: str) -> int:
    n = len(state["versions"])
    v = {"live": state["live"], "a": state["a"], "b": state["b"]}.get(which.lower())
    if v is None:
        v = int(which.lstrip("v"))
    if not 0 <= v <= n:
        raise ValueError(f"version {which!r} -> {v} is not in 0..{n}")
    return v


def version_edits(state: dict, version: int) -> list[list]:
    return [] if version == 0 else [list(e) for e in state["versions"][version - 1]["edits"]]


def skill_files(mods: Path = MODS) -> dict[str, Path]:
    """top-level skill id -> its .sval under mods/ (tools and test modules left out). A copy
    tools/make_specs_classes.py generates from a vanilla skill (the Generosity paladin's Lay on
    Hands and Conviction) keeps the vanilla id, so it is left out too: the id stays vanilla
    and refused, and a regenerate would overwrite the edit anyway."""
    out = {}
    for f in sorted(mods.glob("*/**/*.sval")):
        if f.relative_to(mods).parts[0].startswith(SKIP):
            continue
        text = f.read_text(encoding="utf-8", errors="replace")
        if GENERATED in text:
            continue
        for m in TOP_ID.finditer(text):
            out.setdefault(m.group(1), f)
    return out


def nested_ids(mods: Path = MODS) -> set[str]:
    """ids that only appear deeper than the top level (modifier sub-skills)"""
    ids = set()
    for f in mods.glob("*/**/*.sval"):
        if f.relative_to(mods).parts[0].startswith(SKIP):
            continue
        ids.update(re.findall(r'^\t\t+<string name="id">([^<]+)</string>', f.read_text(encoding="utf-8", errors="replace"), re.M))
    return ids


def bake(edits: list[list], mods: Path = MODS) -> tuple[dict[Path, str], list[str], list[str]]:
    """(file -> new text, refusals, notes). The texts are only meant to be written when there
    are no refusals."""
    from tools.devarena import tooltip_lint
    files = skill_files(mods)
    nested = None
    texts: dict[Path, str] = {}
    before: dict[Path, str] = {}
    refused, notes = [], []
    for sid, level, path, value in edits:
        where = f"{sid}[{level}].{path} = {value}"
        if str(path).startswith("@"):
            refused.append(f"{where}: a composed skill (use tools/devarena/clone_spec.py)")
            continue
        f = files.get(sid)
        if f is None:
            if nested is None:
                nested = nested_ids(mods)
            why = "a modifier sub-skill: edit its parent's file by hand" if sid in nested else \
                "not in any mod (a vanilla skill: HammerwatchPlus does not rebalance vanilla)"
            refused.append(f"{where}: {why}")
            continue
        if f not in texts:
            raw = f.read_text(encoding="utf-8", errors="replace")
            before[f] = raw
            texts[f] = raw.replace("\r\n", "\n")
        new, why = clone_spec.patch_leaf(texts[f], int(level), str(path), str(value))
        if why:
            refused.append(f"{where}: {why} ({f.relative_to(mods.parent)})")
            continue
        texts[f] = new
        notes.append(f"{where} -> {f.relative_to(mods.parent)}")
    out = {}
    for f, text in texts.items():
        text, tnotes = clone_spec.fix_tooltips(text, tooltip_lint.parse_sval_text(before[f].replace("\r\n", "\n")))
        notes += [f"{f.name}: {n}" for n in tnotes]
        out[f] = text.replace("\n", "\r\n") if "\r\n" in before[f] else text
    return out, refused, notes


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", default="live", help="N, live, a or b (default live)")
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--from", dest="sval", help="an override .sval (default the devarena mod's)")
    src.add_argument("--log", help="a game log: use its last override line")
    ap.add_argument("--dry-run", action="store_true", help="print what would change, write nothing")
    a = ap.parse_args(argv)

    if a.log:
        state = overrides.last_in(Path(a.log).read_text(encoding="utf-8", errors="replace"))
        if state is None:
            print(f"no override line in {a.log}")
            return 1
    else:
        state = overrides.from_sval(Path(a.sval or overrides.SVAL).read_text(encoding="utf-8"))
    v = pick(state, a.version)
    edits = version_edits(state, v)
    if not edits:
        print(f"v{v} has no edits; nothing to write")
        return 0
    texts, refused, notes = bake(edits)
    for n in notes:
        print("  " + n)
    if refused:
        print(f"refused, nothing written ({len(refused)} of {len(edits)} edits):")
        for r in refused:
            print("  " + r)
        return 1
    if a.dry_run:
        print(f"dry run: v{v} would change {len(texts)} file(s)")
        return 0
    for f, text in texts.items():
        with open(f, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    print(f"wrote v{v}: {len(edits)} edits into {len(texts)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
