"""Ship check report (docs/devarena/SPEC.md HP6, "Decided during build" 27).

A spec mod is shippable when the game parses it as a named mastery of its base class, every
lang key it shows resolves, the real Subclass Picker NPC offers it and switches the player to
it, its own tooltips show its own numbers (the tooltip lint), and its skills cast. This reads
an hp6-ship run (its da-ship replies in gl.jsonl and run.json's assertions), runs the spec
lint on the mod folder, and writes docs/devarena/ship/<classId>.md.

    python tools/devarena/ship_check.py --run gamelab/results/<time>-hp6-ship-lab
    python tools/devarena/ship_check.py --run <dir> --mod mods/spec-ranger-test --out <file.md>

Exit 0 when every check passes, 1 when one fails, 2 on a bad input.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from tools.devarena import overrides, tooltip_lint  # noqa: E402

SHIP = overrides.REPO / "docs" / "devarena" / "ship"


def ship_replies(run: Path) -> list[dict]:
    """Every da-ship reply in the run's telemetry, in order (a reply follows its rx line)."""
    want, out = set(), []
    for line in (run / "gl.jsonl").read_text(encoding="utf-8", errors="replace").splitlines():
        try:
            d = json.loads(line)
        except ValueError:
            continue
        if d.get("ev") == "rx" and d.get("verb") == "da-ship":
            want.add(d.get("cid"))
        elif d.get("id") in want and "class" in d:
            want.discard(d["id"])
            out.append(d)
    return out


def checks(replies: list[dict], assertions: list[dict], stale: list[dict], linted: int) -> list[tuple[str, bool, str]]:
    first, last = replies[0], replies[-1]
    shown = next((r for r in replies if r.get("picker") and r.get("shows") == first["class"]), None)
    failed = [a["name"] for a in assertions if not a.get("ok")]
    return [
        ("parsed: named, with an icon", bool(first.get("name")) and first.get("icon") is True, f"{first.get('name')!r}"),
        ("a mastery of its base class", bool(first.get("parent")) and first.get("pickerIndex", -1) >= 0,
         f"parent {first.get('parent')}, picker slot {first.get('pickerIndex')} of {first.get('siblings')}"),
        ("every lang key resolves", last.get("unresolvedCount") == 0 and first.get("unresolvedCount") == 0,
         ", ".join(first.get("unresolved") or []) or "none unresolved"),
        ("the Subclass Picker shows it", shown is not None,
         "" if shown is None else f"picked-class {shown.get('picked-class')!r}, active {shown.get('skill-active-name')!r}, "
                                  f"passive {shown.get('skill-passive-name')!r}"),
        ("picking it switches the class", last.get("picked") is True and last.get("playerClass") == first["class"],
         f"player class {last.get('playerClass')}"),
        ("its tooltips show its numbers", not stale, f"{linted} skills linted, {len(stale)} stale"),
        ("the run passed", not failed, "; ".join(failed) or f"{len(assertions)} assertions"),
    ]


def render(run: Path, cls: dict, rows: list[tuple[str, bool, str]], stale: list[dict]) -> str:
    ok = all(r[1] for r in rows)
    out = [f"# Ship check: {cls['class']} ({cls.get('name')})", "",
           f"Generated by `tools/devarena/ship_check.py` from `{run.as_posix()}`. "
           f"Verdict: **{'SHIPPABLE' if ok else 'NOT SHIPPABLE'}**.", "",
           "| Check | | Evidence |", "|---|---|---|"]
    out += [f"| {n} | {'pass' if p else 'FAIL'} | {e} |" for n, p, e in rows]
    out += ["", f"## Skills ({cls.get('skillCount')}, {cls.get('stars')} stars)", "",
            "| Id | Name | Levels | Stars | Tooltip params |", "|---|---|---|---|---|"]
    for s in cls.get("skills", []):
        out.append(f"| {s['id']} | {s['name']} | {s['levels']} | {s['cost']} | {'; '.join(s['params']) or '-'} |")
    if cls.get("skillsCut"):
        out.append("\n(more skills than da-ship's cap)")
    if stale:
        out += ["", "## Stale tooltip params", ""]
        out += [f"- {s['skill']} L{s['level']} {s['param']} shows {s['shown']!r}, fields {s['fields']}" for s in stale]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--run", required=True, help="an hp6-ship run folder")
    ap.add_argument("--mod", help="the spec mod folder (default mods/spec-<id> from the reply)")
    ap.add_argument("--out", help="the report (default docs/devarena/ship/<classId>.md)")
    a = ap.parse_args(argv)
    run = Path(a.run)
    try:
        replies = ship_replies(run)
        assertions = json.loads((run / "run.json").read_text(encoding="utf-8")).get("assertions", [])
    except OSError as e:
        print(f"bad input: {e}")
        return 2
    if not replies:
        print(f"bad input: no da-ship reply in {run / 'gl.jsonl'}")
        return 2
    cls = replies[0]
    mod = Path(a.mod) if a.mod else overrides.REPO / "mods" / ("spec-" + cls["class"].replace("_", "-"))
    try:
        linted, stale = tooltip_lint.lint_spec(tooltip_lint.skill_entries(), mod)
    except ValueError as e:
        print(f"bad input: {e}")
        return 2
    rows = checks(replies, assertions, stale, linted)
    out = Path(a.out) if a.out else SHIP / f"{cls['class']}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(run, cls, rows, stale), encoding="utf-8")
    for n, p, e in rows:
        print(f"  [{'PASS' if p else 'FAIL'}] {n}: {e}")
    print(f"wrote {out}")
    return 0 if all(r[1] for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
