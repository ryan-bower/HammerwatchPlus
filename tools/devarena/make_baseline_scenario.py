"""Write the vanilla bench baseline scenarios (docs/devarena/SPEC.md, row 19).

bench-baseline.json benches every early/mid/end preset in devarena_presets.sval on slot A
(vanilla), 3 pulls of 5 s on the default golem (footman elite, NG+0, 1M pool, standing 24 below it), bot driver,
default rotation. bench-baseline-smoke.json does the first preset of three classes.

    python tools/devarena/make_baseline_scenario.py
    python -m gamelab run devarena/bench-baseline --mode lab
    python tools/devarena/bench.py baseline --log gamelab/results/<run>/logs/pass1.HWR2.exe.log
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRESETS = ROOT / "mods/devarena/tweak/hwp/devarena_presets.sval"
OUT = ROOT / "gamelab/scenarios/devarena"
DA = r"\[HWP:devarena\] "
PULL_S = 5
PULLS = 3


def preset_ids(text: str) -> list[str]:
    ids = re.findall(r'<string name="id">([^<]+)</string>', text)
    return [i for i in ids if re.search(r"/(early|mid|end)$", i)]


def click(dock: str, name: str) -> dict:
    return {"do": "click", "dock": dock, "verify": False, "name": name}


def steps_for(pid: str) -> list[dict]:
    m = "p-" + pid
    rx = re.escape(pid)
    return [
        {"do": "mark", "name": m},
        {"do": "gl", "verb": "da-preset", "args": [pid], "expect": {"ok": True}, "name": "setup: " + pid},
        {"do": "log_has", "pattern": DA + "loadout " + rx + " (ok|mismatch)", "since": m, "timeout": 15,
         "name": pid + " applied"},
        click("bstart", "Start: " + pid),
        {"do": "log_has", "pattern": DA + 'bench-result \\{"bench":[0-9]+,"preset":"' + rx + '"', "since": m,
         "timeout": PULLS * (PULL_S + 8) + 20, "name": pid + " benched"},
        {"do": "log_has", "pattern": DA + r'bench-result \{"bench":[0-9]+,"preset":"' + rx + r'".*"A":\{[^}]*"mean":[1-9]',
         "since": m, "timeout": 2, "name": pid + " dealt damage"},
    ]


def scenario(name: str, ids: list[str], about: str) -> dict:
    head = [
        {"do": "gl", "verb": "mission", "args": ["dark_citadel", 13, "seed=4242", "ngp=0"], "expect": {"ok": True},
         "name": "setup: dark_citadel floor 13"},
        {"do": "wait_phase", "phase": "mission", "timeout": 120},
        {"do": "sleep", "seconds": 3},
        {"do": "gl", "verb": "cull", "args": ["all"], "expect": {"ok": True}, "name": "setup: clear the floor (cheat)"},
        {"do": "key", "key": "f1", "name": "F1"},
        {"do": "sleep", "seconds": 0.5},
        click("tab-bench", "the Bench tab"),
        {"do": "mark", "name": "in"},
        {"do": "key", "key": "f4", "name": "F4: into the room"},
        {"do": "log_has", "pattern": DA + "golem room in", "since": "in", "timeout": 5, "name": "in the room"},
        click("bsrc|versions", "vs: versions"),
        click("bstand|24", "stand: 24 (melee reaches)"),
        click("bmode|bot", "driver: bot"),
        click("bwhich|A", "slots: A (vanilla)"),
        click("bpulls|" + str(PULLS), str(PULLS) + " pulls"),
        click("bsecs|" + str(PULL_S) + "s", str(PULL_S) + " s"),
        {"do": "gl", "verb": "pointer", "args": ["320", "130", "move"], "expect": {"ok": True},
         "name": "setup: the mouse off the dock"},
        {"do": "mark", "name": "bench"},
    ]
    body = [s for pid in ids for s in steps_for(pid)]
    tail = [
        {"do": "bench_csv", "since": "bench", "min_rows": PULLS * len(ids), "name": "CSV: every pull, stats agree"},
        {"do": "log_lacks", "pattern": "\\[HWP:devarena\\].*(error|ERR)", "name": "no devarena errors"},
    ]
    return {"name": name, "about": about, "fixture": "mission-ranger", "mods": ["core", "devarena"],
            "timeout": 300 + len(ids) * (PULLS * (PULL_S + 8) + 20), "steps": head + body + tail}


def main() -> int:
    ids = preset_ids(PRESETS.read_text(encoding="utf-8"))
    smoke = [next(i for i in ids if i.startswith(c)) for c in ("paladin_", "sorcerer_", "warlock_")]
    full = scenario("bench-baseline", ids,
                    f"The vanilla bench baseline (SPEC row 19): all {len(ids)} early/mid/end presets on slot A, "
                    f"{PULLS} pulls of {PULL_S} s, footman elite NG+0 1M, bot, default rotation. Then "
                    "tools/devarena/bench.py baseline --log <run>/logs/pass1.HWR2.exe.log writes "
                    "devarena_baseline.sval. GENERATED by tools/devarena/make_baseline_scenario.py.")
    sm = scenario("bench-baseline-smoke", smoke,
                  "bench-baseline on three presets (one per class family). GENERATED by "
                  "tools/devarena/make_baseline_scenario.py.")
    for d in (full, sm):
        p = OUT / (d["name"] + ".json")
        p.write_text(json.dumps(d, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}: {len(d['steps'])} steps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
