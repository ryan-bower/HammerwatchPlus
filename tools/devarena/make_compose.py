"""Generate the Dev Arena skill composer's catalog (docs/devarena/SPEC.md, "Decided during build" 25).

Output: mods/devarena/tweak/hwp/devarena_compose.sval, read once at boot by
mods/devarena/scripts/HWP/DevArena/Compose.as. It holds the parts a composed skill is built from:

  projectiles  vanilla projectile units a composed skill can shoot. Each carries the binds its
               unit file reads (*-bind keys), copied from the source skill's base "skill.binds",
               so the unit finds them in the composed skill's bind stack. A unit whose binds the
               source does not supply (one set only by an upgrade or modifier) is left out.
  templates    starting skill dicts ("projectile", "nova"). "inherit" lists the keys taken from
               the slot's own vanilla base (anim, blocking, move-speed ...), so the composed skill
               keeps an anim the class has and no ivec2 has to be written by hand.
  snippets     action lists added on cast or on start ("burst", "fan").
  statuses     tweak/buffs/status_effects.sval buffs an on-hit status can apply.
  damage-types Damage keys (physical-bind -> <type>-bind).

    python tools/devarena/make_compose.py          # write the .sval
    python tools/devarena/make_compose.py --check  # exit 1 when it is stale
"""
from __future__ import annotations

import argparse
import glob
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools"))
import hwr_archive  # noqa: E402

GAME = REPO / "gamecode" / "sdk" / "hoh2"
DATA = REPO / "gamecode" / "datatables"
OUT = REPO / "mods" / "devarena" / "tweak" / "hwp" / "devarena_compose.sval"
STATUS_FILE = "tweak/buffs/status_effects.sval"
HEADER = ("<!-- Dev Arena skill composer catalog. GENERATED by tools/devarena/make_compose.py;\n"
          "     edit that script, not this file. -->\n")

# (catalog id, source skill id, the source's bind holding the unit). Hand-picked: the plain
# shooters. Spawners (wiz_meteor, divine_pillars) and rain_of_arrows aim at the ground, not along
# the facing, so they read wrong from a ShootProjectile.
PROJECTILES = [
    ("marked_arrow", "ran_mark", None),
    ("magic_missile", "wiz_magic_missiles", None),
    ("whirling_axe", "whirling_axes", "proj-left-unit"),
    ("elemental_orb", "elemental_orb", None),
    ("lightning_ball", "lightning_ball", "proj-unit"),
    ("grenade", "demolitions_grenade", None),
]
STATUSES = ["marked", "stun_minor", "confusion", "cripple", "slow"]
DAMAGE_TYPES = ["physical", "fire", "ice", "lightning", "poison"]
INHERIT = ["anim", "anim-length", "blocking", "move-speed", "move-speed-mul", "cast-speed-mul", "skill-cost"]
NOVA_FX = "effects/generic/explosions/fire_nova_1.effect?radius=64"

TEMPLATES = {
    "projectile": {
        "about": "shoots the picked projectile along the aim",
        "needs": "proj-unit",
        "skill": {
            "class": "Skills::PlayerSkillDirectional",
            "cooldown": 3000, "castpoint": 150, "mana-cost": 20, "repeating": False,
            "binds": {},
            "actions": {"cast": [{"class": "ShootProjectile", "projectile-bind": "proj-unit", "dist": 8}]},
            "timeline": [150, "cast"],
        },
    },
    "nova": {
        "about": "a ring of damage around the caster",
        "needs": "",
        "skill": {
            "class": "Skills::PlayerSkillDirectional",
            "cooldown": 5000, "castpoint": 200, "mana-cost": 30, "repeating": False,
            "binds": {"nova-dmg": 60, "nova-radius": 64},
            "actions": {"cast": [
                {"class": "SpawnEffect", "effect": NOVA_FX},
                {"class": "Explode", "radius-bind": "nova-radius", "min-radius": 16, "dist-scaling": 1000.0,
                 "effects": [{"class": "Damage", "physical-bind": "nova-dmg"}]},
            ]},
            "timeline": [200, "cast"],
        },
    },
}

SNIPPETS = {
    "burst": {
        "about": "an explosion around the caster",
        "needs": "",
        "binds": {"burst-dmg": 40, "burst-radius": 48},
        "actions": [
            {"class": "SpawnEffect", "effect": "effects/generic/explosions/fire_nova_1.effect?radius=48"},
            {"class": "Explode", "radius-bind": "burst-radius", "min-radius": 8, "dist-scaling": 1000.0,
             "effects": [{"class": "Damage", "physical-bind": "burst-dmg"}]},
        ],
    },
    "fan": {
        "about": "two more projectiles at -15 and +15 degrees",
        "needs": "proj-unit",
        "binds": {},
        "actions": [
            {"rot-add": -15},
            {"class": "ShootProjectile", "projectile-bind": "proj-unit", "dist": 8},
            {"rot-add": 30},
            {"class": "ShootProjectile", "projectile-bind": "proj-unit", "dist": 8},
            {"rot-add": -15},
        ],
    },
}


def skills_by_id() -> dict[str, dict]:
    out = {}
    for p in glob.glob(str(DATA / "players" / "*" / "skills" / "*.sval.json")):
        d = json.loads(Path(p).read_text(encoding="utf-8"))
        if isinstance(d, dict) and "id" in d:
            out[d["id"]] = d
    return out


def unit_text(rel: str, seen: set[str] | None = None) -> str:
    """A unit file with its %include files appended (they hold the bind reads too)."""
    seen = seen if seen is not None else set()
    p = GAME / rel
    if rel in seen or not p.is_file():
        return ""
    seen.add(rel)
    t = p.read_text(encoding="utf-8", errors="replace")
    for inc in re.findall(r'%include "([^"]+)"', t):
        t += unit_text(inc, seen)
    return t


def unit_binds(rel: str) -> list[str]:
    return sorted(set(re.findall(r'name="[a-z0-9-]+-bind">([^<]+)<', unit_text(rel))))


def needed_binds(rel: str, binds: dict, seen: set[str] | None = None) -> tuple[list[str], list[str]]:
    """(binds the unit reads, transitively through unit-valued binds; the ones `binds` lacks)."""
    seen = seen if seen is not None else set()
    if rel in seen:
        return [], []
    seen.add(rel)
    need, miss = [], []
    for b in unit_binds(rel):
        need.append(b)
        if b not in binds or binds[b] is None:
            miss.append(b)
            continue
        v = binds[b]
        if isinstance(v, str) and v.endswith(".unit"):
            n2, m2 = needed_binds(v, binds, seen)
            need += n2
            miss += m2
    return need, miss


def projectiles(skills: dict[str, dict]) -> tuple[list[dict], list[str]]:
    rows, notes = [], []
    for cid, src, bind in PROJECTILES:
        d = skills.get(src)
        if d is None:
            notes.append(f"{cid}: no skill {src}")
            continue
        base = d.get("skill") or {}
        binds = dict(base.get("binds") or {})
        if bind:
            unit = binds.get(bind)
        else:
            unit = None
            for a in (base.get("actions") or {}).get("cast", []) or []:
                if isinstance(a, dict) and str(a.get("class", "")).startswith("ShootProjectile"):
                    unit = a.get("projectile") or binds.get(a.get("projectile-bind", ""))
                    break
            unit = unit or base.get("projectile")
        if not unit or not (GAME / unit).is_file():
            notes.append(f"{cid}: unit {unit!r} not found")
            continue
        need, miss = needed_binds(unit, binds)
        if miss:
            notes.append(f"{cid}: {unit} reads binds {src} does not set: {', '.join(sorted(set(miss)))}")
            continue
        keep = {k: binds[k] for k in sorted(set(need))}
        dmg = next((k for k in sorted(keep) if "dmg" in k and isinstance(keep[k], (int, float))
                    and not isinstance(keep[k], bool) and "mul" not in k), "")
        rows.append({"id": cid, "from": src, "unit": unit, "dmg-bind": dmg, "binds": keep})
    return rows, notes


def statuses() -> list[str]:
    t = (GAME / STATUS_FILE).read_text(encoding="utf-8", errors="replace")
    have = set(re.findall(r"%block \w+ (\w+)", t)) | set(re.findall(r'<dict name="(\w+)">', t))
    missing = [s for s in STATUSES if s not in have]
    if missing:
        raise SystemExit(f"{STATUS_FILE} lacks {missing}")
    return list(STATUSES)


def catalog() -> tuple[dict, list[str]]:
    rows, notes = projectiles(skills_by_id())
    tmpl = {k: {"about": v["about"], "needs": v["needs"], "inherit": list(INHERIT), "skill": v["skill"]}
            for k, v in TEMPLATES.items()}
    return {
        "schema": 1,
        "status-file": STATUS_FILE,
        "projectiles": rows,
        "templates": tmpl,
        "snippets": SNIPPETS,
        "statuses": statuses(),
        "damage-types": list(DAMAGE_TYPES),
    }, notes


def render(cat: dict) -> str:
    return HEADER + hwr_archive.svalue_to_xml(cat) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the .sval is stale")
    a = ap.parse_args(argv)
    cat, notes = catalog()
    for n in notes:
        print("skipped", n)
    text = render(cat)
    if a.check:
        old = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if old != text:
            print(f"{OUT.relative_to(REPO)} is stale: run python tools/devarena/make_compose.py")
            return 1
        print(f"{OUT.relative_to(REPO)} is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}: {len(cat['projectiles'])} projectiles, {len(cat['templates'])} templates, "
          f"{len(cat['snippets'])} snippets, {len(cat['statuses'])} statuses")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
