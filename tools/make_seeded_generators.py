"""make_seeded_generators.py - gamelab-hands overrides that make generated floors seedable.

The dungeon generator draws from the engine's global randi()/randf(), and that RNG is not
private to the generator: MissionGameMode::Generate runs while another thread draws from it
(seed-repeat 20261018-162919: srand, a CPU-only spin, then randi() inside Generate gives a
different value every load; the same probe in Start gives the seeded sequence's 2nd value).
So srand cannot replay a layout. Instead every Generators/*.as file that draws is copied into
mods/gamelab-hands/scripts/Generators/ with its draws routed through GameLab::GenRandi /
GenRandf / GenRandDir / GenRollRound (mods/gamelab-hands/scripts/GameLab/Hands.as). Those use
a private RandomSequence while a `mission ... seed=N` floor is generating, and the engine's
own functions otherwise, so the copies behave as vanilla when no seed is active.

Each copy is a declared override (module.json) with its pristine `<file>.orig` beside it
(docs/modules.md rule 1), so `tools/build.py --check` flags a game update.

    python tools/make_seeded_generators.py          # (re)write the copies, .orig and module.json
    python tools/make_seeded_generators.py --check  # exit 1 when a copy is stale or missing
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gamepaths as paths  # noqa: E402

SRC = paths.REPO / "gamecode" / "sdk" / "hoh2" / "scripts" / "Generators"
MOD = paths.REPO / "mods" / "gamelab-hands"
DST = MOD / "scripts" / "Generators"
CALLS = {"randi": "GameLab::GenRandi", "randf": "GameLab::GenRandf",
         "randdir": "GameLab::GenRandDir", "roll_round": "GameLab::GenRollRound"}
CALL_RE = re.compile(r"(?<![\w:.])(" + "|".join(CALLS) + r")\s*\(")
HEADER = ("// GENERATED by tools/make_seeded_generators.py from the base file of the same path:\n"
          "// RNG calls routed through GameLab::GenRand* (Hands.as). Do not edit; re-run the tool.\n")


def decode(b: bytes) -> str:
    return b.decode("utf-8-sig" if b.startswith(b"\xef\xbb\xbf") else "utf-8")


def plan() -> dict[str, tuple[bytes, bytes]]:
    """rel path -> (patched copy, pristine base) for every generator file that draws."""
    out = {}
    for f in sorted(SRC.glob("*.as")):
        base = f.read_bytes()
        text = decode(base)
        patched, n = CALL_RE.subn(lambda m: CALLS[m.group(1)] + "(", text)
        if n:
            nl = "\r\n" if "\r\n" in text else "\n"
            out[f"scripts/Generators/{f.name}"] = ((HEADER.replace("\n", nl) + patched).encode("utf-8"), base)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = plan()
    cfg_path = MOD / "module.json"
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    stale = []
    for rel, (copy, base) in want.items():
        for path, data in ((MOD / rel, copy), (MOD / (rel + ".orig"), base)):
            if not path.is_file() or path.read_bytes() != data:
                stale.append(path)
                if not a.check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(data)
    extra = [p for p in DST.glob("*.as") if f"scripts/Generators/{p.name}" not in want] if DST.is_dir() else []
    others = [o for o in cfg.get("overrides", []) if not o.startswith("scripts/Generators/")]
    overrides = others + sorted(want)
    if cfg.get("overrides") != overrides:
        stale.append(cfg_path)
        if not a.check:
            cfg["overrides"] = overrides
            cfg_path.write_text(json.dumps(cfg, indent=2) + "\n", encoding="utf-8")
    if not a.check:
        for p in extra:
            p.unlink()
            orig = p.with_name(p.name + ".orig")
            if orig.exists():
                orig.unlink()
    for p in stale + extra:
        print(("STALE  " if a.check else "wrote  ") + str(p.relative_to(paths.REPO)))
    print(f"{len(want)} generator files routed through GameLab::GenRand*")
    return 1 if a.check and (stale or extra) else 0


if __name__ == "__main__":
    sys.exit(main())
