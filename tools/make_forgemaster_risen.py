TAG_RE = re.compile(r"""<(/?)([A-Za-z_][\w:.-]*)((?:[^<>"'/]|/(?!>)|"[^"]*"|'[^']*')*)(/?)>""")


def well_formed(text):
    """None, or why the game would refuse the unit: an unclosed comment, or tags that do not
    nest. The game's XML is lenient (a bare &, attributes without a space between them, a
    repeated attribute all load), so this checks the structure only: %defblock bodies on their
    own, every other % line dropped (each %if branch nests by itself)."""
    text = COMMENT_RE.sub("", text)
    if "<!--" in text:
        return "unclosed comment at line %d" % (text[:text.find("<!--")].count("\n") + 1)
    blocks = {}

    def defblock(m):
        blocks[m.group(1)] = m.group(2)
        return "\n" * m.group(0).count("\n")
    text = re.sub(r"^[ \t]*%defblock[ \t]+(\S+)[^\n]*\n(.*?)^[ \t]*%endblock[^\n]*\n?", defblock, text, flags=re.M | re.S)

    def expand(frag, depth):
        # a %block is a fragment pasted where it is used (it may open a tag the unit closes)
        if depth > 8:
            return frag
        return re.sub(r"^[ \t]*%block[ \t]+(\S+)[^\n]*", lambda m: expand(blocks.get(m.group(1), ""), depth + 1), frag, flags=re.M)
    text = re.sub(r"^[ \t]*%(?!block\b)[^\n]*", "", expand(text, 0), flags=re.M)
    stack = []
    for m in TAG_RE.finditer(text):
        closing, tag, _, selfclose = m.groups()
        line = text[:m.start()].count("\n") + 1
        if closing:
            if not stack or stack[-1] != tag:
                return f"</{tag}> at line {line} closes {'<' + stack[-1] + '>' if stack else 'nothing'}"
            stack.pop()
        elif not selfclose:
            stack.append(tag)
    if stack:
        return f"<{stack[-1]}> never closed"
    return None


def enemy_units():
    """(rel, text) of every unit under actors/ whose behavior is on team enemy"""
    out = []
    for p in sorted(ACTORS.rglob("*.unit")):
        text = COMMENT_RE.sub("", p.read_text(encoding="utf-8", errors="replace"))
        if TEAM_RE.search(text):
            out.append((p.relative_to(ACTORS).as_posix(), text))
    return out


def raisable(rel, text):
    if any(re.search(x, rel) for x in EXCLUDE):
        return False
    m = re.search(r'<behavior class="([^"]+)"', text)
    return bool(m) and m.group(1) in CLASSES


def inline_includes(text, seen=()):
    def sub(m):
        path = m.group(1)
        if path in seen:
            return ""
        f = REPO / "gamecode/sdk/hoh2" / path
        if not f.is_file():
            sys.exit(f"missing include {path}")
        inc = COMMENT_RE.sub("", f.read_text(encoding="utf-8", errors="replace"))
        return inline_includes(inc, seen + (path,)).rstrip("\n") + "\n"
    return INCLUDE_RE.sub(sub, text)


def absolutize(text, rel):
    d = "actors/" + rel.rsplit("/", 1)[0] + "/" if "/" in rel else "actors/"
    return text.replace('="./', '="' + d)


def drop_bossbar(text):
    while True:
        a = text.find('<dict name="bossbar">')
        if a < 0:
            return text
        b = text.find("</dict>", a)
        start = text.rfind("\n", 0, a) + 1
        end = text.find("\n", b) + 1
        text = text[:start] + text[end:]


def clamp_circles(text):
    def sub(m):
        tag = m.group(0)
        if 'sensor="true"' in tag:
            return tag
        return re.sub(r'radius="(\d+(?:\.\d+)?)"', lambda r: f'radius="{min(float(r.group(1)), RADIUS_MAX):g}"', tag)
    return CIRCLE_RE.sub(sub, text)


PLAYER_TARGET_RE = re.compile(r"<(s|string)>tag</(?:s|string)>\s*<(?:s|string)>has</(?:s|string)>\s*<a>\s*<(?:s|string)>player</(?:s|string)>\s*</a>")
# a boss skill's `flag is <arena flag>` conditional line (CondFlag on the floor's flags, which the
# arena's script sets: boss_skills by the Face's fight, totem_skills by the totem poles', room_4 by
# the Bandit King's last room). Its own line in every boss file; a `<a>...</a>` transition is not matched.
ARENA_FLAG_RE = re.compile(r"^[ \t]*<(?:s|string)>flag</(?:s|string)>\s*<(?:s|string)>is</(?:s|string)>\s*"
                           r"<(?:s|string)>(?:boss_skills|totem_skills|room_4)</(?:s|string)>[ \t]*\r?\n", re.M)


def tags_of(text):
    m = TAGS_RE.search(text)
    return re.findall(r"<(?:string|s)>([^<]+)</(?:string|s)>", m.group(0)) if m else []


def common(rel, text):
    """the enemy's text made loadable from the mod's folder"""
    text = absolutize(inline_includes(text), rel)
    return GENERATED.format(rel=rel) + "\n" + text


def risen_unit(rel, text):
    tags = tags_of(text)
    text = common(rel, text)
    cls = re.search(r'<behavior class="([^"]+)"', text).group(1)
    text = text.replace(f'<behavior class="{cls}"', f'<behavior class="{CLASSES[cls]}"', 1)
    text = TEAM_RE.sub('<string name="team">player</string>', text)
    for name in DROP_PARAMS:
        text = re.sub(r'^[ \t]*<\w+ name="' + name + r'">[^\n]*</\w+>[ \t]*\r?\n', "", text, flags=re.M)
    text = drop_bossbar(text)
    text = text.replace('<string name="team">player</string>\n', '<string name="team">player</string>\n' + LEASHES, 1)

    def tags_sub(m):
        block = m.group(0)
        if "enemy" in tags:
            block = re.sub(r"<(string|s)>enemy</(?:string|s)>", r"<\1>summon</\1><\1>hwp_risen</\1>", block, count=1)
        else:
            block = block.replace("</array>", "<string>summon</string><string>hwp_risen</string></array>", 1)
        return block
    if TAGS_RE.search(text):
        text = TAGS_RE.sub(tags_sub, text, count=1)
    else:
        text = text.replace(LEASHES, LEASHES + '\t\t<array name="tags"><string>summon</string><string>hwp_risen</string></array>\n', 1)
    if rel in BOSS_HP:
        text = re.sub(r'<int name="hp">\d+</int>', f'<int name="hp">{BOSS_HP[rel]}</int>', text, count=1)
    # 31 attack skills in 15 units (the Face's spews, the Bandit King's, the Judges', the Spider
    # Queen's, the necromancers' ...) demand a player-tagged target, which a risen's enemy targets
    # never are: they aim at anything that isn't a player instead (bosses 20261022-052506: the
    # risen Face kept its target and never attacked). The two effect-level `conditional`s with the
    # same check (Dace Arden's chain link, the Spider Queen's spew_web, both `cond-target-self`
    # false: tested on the unit the effect hits) flip too, so the risen's link and web take the
    # non-players they hit; a skill-level `conditional` never asks this of the caster itself.
    text = PLAYER_TARGET_RE.sub(lambda mm: "<{0}>tag</{0}><{0}>hasnt</{0}><a><{0}>player</{0}></a>".format(mm.group(1)), text)
    # the arena flags go: a risen fights wherever its owner is, with no arena script to set them.
    # The boss's own phase flags (stage2, boss_dead ...) stay: its kept SetFlag effects set them.
    text = ARENA_FLAG_RE.sub("", text)
    if '<array name="movements">' not in text and IMMOBILE_RE.search(text):
        text = MIN_RANGE_RE.sub("", text)
    # a summon's look: the NPC silhouette and map dot, the ring in the summon bar's colour
    text = ENEMY_MATERIAL_RE.sub(f'material="{RISEN_MATERIAL}"', text)
    text = ENEMY_MINIMAP_RE.sub(RISEN_MINIMAP, text)
    text = text.replace(ELITE_MARKER, MARKER_REL + "elite_marker.unit:")
    return clamp_circles(text)


def shape_flags(m):
    """a collision shape every raycast passes: shoot-through (RaycastType::Shot: the Priest's beam,
    the shots), aim-through and charge-through all true"""
    tag = m.group(0)
    end = "/>" if tag.endswith("/>") else ">"
    body = tag[:-len(end)].rstrip()
    for attr in THROUGH:
        if re.search(attr + r'="', body):
            body = re.sub(attr + r'="[^"]*"', attr + '="true"', body)
        else:
            body += f' {attr}="true"'
    return body + (" " if end == "/>" else "") + end


def still_sprite(m):
    """the sprite frozen: no looping, its first frame only (a sprite whose frames sit in %if
    branches keeps them all, unlooped, so no branch is left without a frame)"""
    block = m.group(0)
    head_end = block.find(">") + 1
    block = ANIM_ATTR_RE.sub("", block[:head_end]) + block[head_end:]
    if re.search(r"^[ \t]*%", block, re.M):
        return block
    frames = list(FRAME_RE.finditer(block))
    for f in reversed(frames[1:]):
        block = block[:f.start()] + block[f.end():]
    return block


def dead_scenes(text):
    """the enemy's scenes as a body: still, dark, map-less, shot through (the docstring's list)"""
    for rx in (MINIMAP_LINE_RE, ELITE_LINE_RE, EFFECT_RE, EFFECT_BLOCK_RE, LIGHT_RE, PARTICLES_RE):
        text = rx.sub("", text)
    text = SPRITE_RE.sub(still_sprite, text)
    text = SCENE_TAG_RE.sub(lambda m: ANIM_ATTR_RE.sub("", m.group(0)), text)
    text = ENEMY_MATERIAL_RE.sub(f'material="{BODY_MATERIAL}"', text)
    text = SHAPE_RE.sub(shape_flags, text)
    if "<sprite" not in text:
        # nothing visible is left (a wisp is effects only): the still core in every idle scene
        text = re.sub(r'<scene name="idle[^"]*"[^>]*>', lambda m: m.group(0) + DEAD_CORE, text)
    return text


def body_unit(rel, text):
    tags = tags_of(text)
    idle = re.search(r'<string name="anim-idle">([^<]+)</string>', text)
    text = common(rel, text)
    a = text.find("<behavior ")
    b = text.find("</behavior>", a) + len("</behavior>")
    behavior = (f'<behavior class="{BODY_CLASS}">\n'
                f'\t\t<string name="source">{FORGE}risen/{rel}</string>\n'
                f'\t\t<bool name="elite">{"true" if "elite" in tags else "false"}</bool>\n'
                f'\t\t<bool name="boss">{"true" if "boss" in tags else "false"}</bool>\n'
                f'\t\t<string name="idle">{idle.group(1) if idle else "idle"}</string>\n'
                '\t</behavior>')
    return dead_scenes(text[:a] + behavior + text[b:])


def units_as(enemies, rels):
    lines = ["// GENERATED by tools/make_forgemaster_risen.py; do not edit.",
             "// ENEMY_UNITS: every actor on team enemy (a risen's SpawnUnit of one of these is dropped,",
             "// Forgemaster.as StripActions). RISEN_RELS: the raisable ones, under actors/, with a risen",
             "// and a body unit in players/hwp/specs/forgemaster/.",
             "namespace HWP", "{", "\tnamespace Specs", "\t{",
             "\t\tconst array<string> ENEMY_UNITS = {"]
    # no comma after the last entry: AngelScript makes a trailing comma one more, empty, element
    # (RISEN_RELS had 142 entries for 141 enemies, the last "")
    lines += [",\n".join(f'\t\t\t"actors/{rel}"' for rel, _ in enemies)]
    lines += ["\t\t};", "", "\t\tconst array<string> RISEN_RELS = {"]
    lines += [",\n".join(f'\t\t\t"{rel}"' for rel in rels)]
    lines += ["\t\t};", "\t}", "}", ""]
    return "\n".join(lines)


def ignore_text(current):
    block = "\n".join([IGNORE_BEGIN] + ["/" + FORGE + d + "/" for d in ("risen", "bodies", "marker")] + [IGNORE_END])
    a, b = current.find(IGNORE_BEGIN), current.find(IGNORE_END)
    if a >= 0 and b > a:
        return current[:a] + block + current[b + len(IGNORE_END):]
    return current.rstrip("\n") + ("\n" if current.strip() else "") + block + "\n"


def image_module():
    try:
        from PIL import Image
    except ImportError:  # pragma: no cover
        sys.exit("Pillow is missing (the marker PNGs need it): run `uv sync` / python -m gamelab doctor --fix")
    return Image


def png_bytes(im):
    buf = BytesIO()
    im.save(buf, format="PNG")
    return buf.getvalue()


def ring_png():
    """The elite ring sheet in RING_COLOR, drawn here rather than recoloured from the base game's
    (no base-game art is shipped): four 32 px frames side by side, as actors/shared/elite_marker.png
    lays them out for the elite_marker_<n>.effect frames, each a thin ring with four spikes. RING_RADII
    are the base frames' ring radii, so the ring sits where an elite's does."""
    Image = image_module()
    from PIL import ImageDraw
    k = 8  # the shape is drawn at 8x as a mask and scaled down, for smooth edges in one exact colour
    big = Image.new("L", (32 * len(RING_RADII) * k, 32 * k), 0)
    d = ImageDraw.Draw(big)
    for i, r in enumerate(RING_RADII):
        cx, cy = (i * 32 + 16) * k, 16 * k
        d.ellipse((cx - r * k, cy - r * k, cx + r * k, cy + r * k), outline=255, width=round(1.5 * k))
        for n in range(4):
            a = math.pi / 4 + n * math.pi / 2
            tip, base, half = (r + 3.2) * k, (r + 0.2) * k, 1.9 * k
            ux, uy = math.cos(a), math.sin(a)
            d.polygon([(cx + ux * tip, cy + uy * tip),
                       (cx + ux * base - uy * half, cy + uy * base + ux * half),
                       (cx + ux * base + uy * half, cy + uy * base - ux * half)], fill=255)
    im = Image.new("RGBA", (big.width // k, big.height // k), RING_COLOR + (0,))
    im.putalpha(big.resize(im.size, Image.Resampling.BOX))
    return png_bytes(im)


def core_png():
    """A still grey orb, CORE_SIZE px, centred in a CORE_TEX square (power of two, or the game refuses
    the texture at boot): a dead electric orb is its core. Drawn here (no base-game art is shipped):
    a darker middle, a lit rim and a soft edge, at CORE_GREY brightness."""
    Image = image_module()
    im = Image.new("RGBA", (CORE_TEX, CORE_TEX), (0, 0, 0, 0))
    px = im.load()
    c, rad = CORE_TEX / 2, CORE_SIZE / 2
    for y in range(CORE_TEX):
        for x in range(CORE_TEX):
            t = math.hypot(x + 0.5 - c, y + 0.5 - c) / rad
            if t >= 1.0:
                continue
            light = 0.45 + 0.55 * t ** 3 - 0.25 * max(0.0, (y + 0.5 - c) / rad)  # rim lit, lower half shaded
            grey = max(0, min(255, round(255 * CORE_GREY * light)))
            px[x, y] = (grey, grey, grey, round(255 * min(1.0, (1.0 - t) * 6)))
    return png_bytes(im)


def marker_files():
    """{path: text|bytes} of players/hwp/specs/forgemaster/marker/"""
    out = {}
    unit = (SHARED / "elite_marker.unit").read_text(encoding="utf-8")
    out[MARKER / "elite_marker.unit"] = (GENERATED.format(rel="shared/elite_marker.unit") + "\n"
                                         + unit.replace('src="actors/shared/elite_marker_', f'src="{MARKER_REL}elite_marker_'))
    for n in (14, 16, 20):
        eff = (SHARED / f"elite_marker_{n}.effect").read_text(encoding="utf-8")
        eff = eff.replace('texture="./elite_marker.png"', f'texture="{MARKER_REL}elite_marker.png"')
        eff = eff.replace('material="./shared.mats:elite"', 'material="actors/shared/shared.mats:elite"')
        out[MARKER / f"elite_marker_{n}.effect"] = eff
    out[MARKER / "elite_marker.png"] = ring_png()
    out[MARKER / "dead_core.png"] = core_png()
    return out


def build():
    """{path: text|bytes} of everything this tool writes"""
    enemies = enemy_units()
    out = {}
    rels = []
    for rel, text in enemies:
        if not raisable(rel, text):
            continue
        rels.append(rel)
        out[RISEN / rel] = risen_unit(rel, text)
        out[BODIES / rel] = body_unit(rel, text)
    out.update(marker_files())
    out[UNITS_AS] = units_as(enemies, rels)
    out[GITIGNORE] = ignore_text(GITIGNORE.read_text(encoding="utf-8") if GITIGNORE.is_file() else "")
    return out, rels


def same(p, t):
    if not p.is_file():
        return False
    return p.read_bytes() == t if isinstance(t, bytes) else p.read_text(encoding="utf-8") == t


def main(argv):
    if not ACTORS.is_dir():
        sys.exit("gamecode/sdk/hoh2/actors missing: run tools/bootstrap.py first")
    out, rels = build()
    if "--list" in argv:
        print("\n".join(rels))
        print(f"{len(rels)} raisable")
        return
    bad = [(p, why) for p, t in out.items() if p.suffix == ".unit" and (why := well_formed(t))]
    for p, why in bad:
        print("malformed:", p.relative_to(REPO).as_posix(), "|", why)
    if bad:
        sys.exit(f"{len(bad)} generated unit(s) would not parse; nothing written")
    if "--check" in argv:
        stale = [p for p, t in out.items() if not same(p, t)]
        extra = [p for d in OUT_DIRS if d.is_dir() for p in d.rglob("*") if p.is_file() and p not in out]
        for p in stale + extra:
            print("stale:", p.relative_to(REPO).as_posix())
        if stale or extra:
            sys.exit(1)
        return
    for d in OUT_DIRS:
        if d.is_dir():
            for p in d.rglob("*"):
                if p.is_file() and p not in out:
                    p.unlink()
    for p, t in out.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not same(p, t):
            if isinstance(t, bytes):
                p.write_bytes(t)
            else:
                p.write_text(t, encoding="utf-8", newline="\n")
    print(f"wrote {len(rels)} risen + {len(rels)} body units, the marker files, {UNITS_AS.relative_to(REPO).as_posix()}")


if __name__ == "__main__":
    main(sys.argv[1:])
