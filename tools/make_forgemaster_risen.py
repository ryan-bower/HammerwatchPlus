"""make_forgemaster_risen.py - the Devil Forgemaster's risen summons and intact bodies (mods/specs).

For every raisable enemy unit under gamecode/sdk/hoh2/actors/ (team enemy; a CompositeActor,
StateActor or TransferDamage actor; not on the EXCLUDE list) two units are written into mods/specs:

  players/hwp/specs/forgemaster/risen/<rel>    the summon: the enemy's own file with its behavior
      class swapped for HWPSpecsRisen / HWPSpecsRisenState (scripts/HWP/Specs/Forgemaster.as),
      team player, the summon tags and leashes, and no loot, experience, respawn or boss bar.
      Bosses get the BOSS_HP table and every solid collision circle is clamped to RADIUS_MAX so
      the summon fits the hallways (there is no radius setter at runtime).
  players/hwp/specs/forgemaster/bodies/<rel>   the intact body: HWPSpecsBody with the enemy's
      scenes, lying gray on the floor until raised, eaten or 60 s pass.

The enemy's `%include "actors/..."` lines are inlined, because the game resolves "./x" paths
against the unit being loaded (horde_soldier/horde_soldier.inc says ./horde_soldier/...), so a
copy in another folder needs them absolute: every ="./x" becomes ="actors/<unit dir>/x".
scripts/HWP/Specs/Forgemaster_Units.as gets the enemy unit set (a risen's SpawnUnit actions
that spawn one of these are dropped) and the raisable list.

The unit copies derive from the player's own install, so they are gitignored (a marked block in
mods/specs/.gitignore) and remade here, like tools/class_units.py's copies.

    python tools/make_forgemaster_risen.py          # write
    python tools/make_forgemaster_risen.py --check  # exit 1 when anything on disk differs
    python tools/make_forgemaster_risen.py --list   # the raisable units, write nothing
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ACTORS = REPO / "gamecode/sdk/hoh2/actors"
MOD = REPO / "mods/specs"
RISEN = MOD / "players/hwp/specs/forgemaster/risen"
BODIES = MOD / "players/hwp/specs/forgemaster/bodies"
UNITS_AS = MOD / "scripts/HWP/Specs/Forgemaster_Units.as"
GITIGNORE = MOD / ".gitignore"

GENERATED = "<!-- GENERATED by tools/make_forgemaster_risen.py from actors/{rel}; do not edit -->"
IGNORE_BEGIN = "# >>> tools/make_forgemaster_risen.py (generated from the HoH2 base; do not edit)"
IGNORE_END = "# <<< tools/make_forgemaster_risen.py"

CLASSES = {"CompositeActorBehavior": "HWPSpecsRisen", "StateActorBehavior": "HWPSpecsRisenState",
           "TransferDamageActor": "HWPSpecsRisenState"}

# not raisable: the mission-final bosses (the next stop is town), fight props and health dummies,
# spawners, traps and the banners (the bannermen themselves rise)
EXCLUDE = [
    r"^bosses/boss_spider_queen/", r"^bosses/boss_wraith/", r"^bosses/boss_avatar/", r"^bosses/spirits/",
    r"^bosses/boss_bandit/boss_bandit\.unit$", r"^bosses/boss_bandit/boss_bandit_mirror\.unit$",
    r"^bosses/boss_totempole/totem_pylon\.unit$", r"^bosses/bone_serpent/boss_serpent_health\.unit$",
    r"^bosses/bone_serpent/tower_test\.unit$", r"^bosses/boss_judges/boss_harbingers_health\.unit$",
    r"^bosses/boss_face/cultist_targeter\.unit$", r"^humans/cult/cult_brother_boss_face\.unit$",
    r"(^|/)spawner_", r"(^|/)summon_spawner_", r"^misc/treeline_spawner\.unit$", r"^misc/dimension_rift/",
    r"^undead/horde/projectiles/", r"^misc/bone_blockade/", r"^beasts/wasps/wasp_nest\.unit$",
    r"^beasts/beetles/burrowing_beetles_", r"^undead/bannermen/banner_", r"^aberrations/plants/vine\.unit$",
]

# a boss summon's health (the enemy's is its arena fight's); the scripts scale it by the skill level
BOSS_HP = {
    "bosses/boss_judges/boss_judges_heavy.unit": 6000, "bosses/boss_judges/boss_judges_caster.unit": 6000,
    "bosses/bone_serpent/boss_serpent.unit": 8000, "bosses/boss_face/boss_face.unit": 5000,
    "bosses/boss_arista/boss_arista.unit": 6000, "bosses/boss_bandit/boss_bandit_encounter.unit": 4000,
    "bosses/boss_totempole/boss_totempole_earth.unit": 3000, "bosses/boss_totempole/boss_totempole_fire.unit": 3000,
    "bosses/boss_totempole/boss_totempole_ice.unit": 3000, "bosses/boss_totempole/boss_totempole_lightning.unit": 3000,
}
RADIUS_MAX = 10
# single-line params an enemy has that a summon must not (the leashes are set anew)
# a unit that cannot move (its one movement is PassiveMovement): the heavy ballista's shot wants its
# target 30+ away, so a brute that walked up to the risen ballista could never be hit (plan-forgemaster
# 20261022-085643); a summon that cannot step back keeps no minimum range
IMMOBILE_RE = re.compile(r'<dict name="movement">\s*<string name="class">PassiveMovement</string>')
MIN_RANGE_RE = re.compile(r'^[ \t]*<int name="min-range">\d+</int>[ \t]*\r?\n', re.M)
DROP_PARAMS = ("experience-reward", "loot", "respawn-time", "aggro-range", "max-range", "hide-health", "drop-target-range")
LEASHES = ('\t\t<int name="aggro-range">300</int>\n\t\t<int name="max-range">500</int>\n'
           '\t\t<int name="aggro-leash">300</int>\n\t\t<int name="teleport-leash">350</int>\n')

INCLUDE_RE = re.compile(r'^[ \t]*%include "(actors/[^"]+)"[ \t]*(?:\r?\n|\Z)', re.M)
TEAM_RE = re.compile(r'<string name="team">enemy</string>')
TAGS_RE = re.compile(r'<array name="tags">.*?</array>', re.S)
CIRCLE_RE = re.compile(r"<circle\b[^>]*>")
# XML comments go first: a commented-out `<behavior class="StateActorBehavior">` (phantom_rogue)
# was what the class detection and the body's behavior swap found, which left an unclosed
# comment and a unit the game could not parse (it crashed on the load)
COMMENT_RE = re.compile(r"<!--.*?-->", re.S)


TAG_RE = re.compile(r"""<(/?)([A-Za-z_][\w:.-]*)((?:[^<>"'/]|/(?!>)|"[^"]*"|'[^']*')*)(/?)>""")


def well_formed(text):
    """None, or why the game would refuse the unit: an unclosed comment, or tags that do not
    nest. The game's XML is lenient (a bare &, attributes without a space between them, a
    repeated attribute all load), so this checks the structure only: %defblock bodies on their
    own, every other % line dropped (each %if branch nests by itself)."""
    text = COMMENT_RE.sub("", text)
    if "<!--" in text:
        return "unclosed comment at line %d" % (text[:text.find("<!--")].count("\n") + 1)
    blocks = {}

    def defblock(m):
        blocks[m.group(1)] = m.group(2)
        return "\n" * m.group(0).count("\n")
    text = re.sub(r"^[ \t]*%defblock[ \t]+(\S+)[^\n]*\n(.*?)^[ \t]*%endblock[^\n]*\n?", defblock, text, flags=re.M | re.S)

    def expand(frag, depth):
        # a %block is a fragment pasted where it is used (it may open a tag the unit closes)
        if depth > 8:
            return frag
        return re.sub(r"^[ \t]*%block[ \t]+(\S+)[^\n]*", lambda m: expand(blocks.get(m.group(1), ""), depth + 1), frag, flags=re.M)
    text = re.sub(r"^[ \t]*%(?!block\b)[^\n]*", "", expand(text, 0), flags=re.M)
    stack = []
    for m in TAG_RE.finditer(text):
        closing, tag, _, selfclose = m.groups()
        line = text[:m.start()].count("\n") + 1
        if closing:
            if not stack or stack[-1] != tag:
                return f"</{tag}> at line {line} closes {'<' + stack[-1] + '>' if stack else 'nothing'}"
            stack.pop()
        elif not selfclose:
            stack.append(tag)
    if stack:
        return f"<{stack[-1]}> never closed"
    return None


def enemy_units():
    """(rel, text) of every unit under actors/ whose behavior is on team enemy"""
    out = []
    for p in sorted(ACTORS.rglob("*.unit")):
        text = COMMENT_RE.sub("", p.read_text(encoding="utf-8", errors="replace"))
        if TEAM_RE.search(text):
            out.append((p.relative_to(ACTORS).as_posix(), text))
    return out


def raisable(rel, text):
    if any(re.search(x, rel) for x in EXCLUDE):
        return False
    m = re.search(r'<behavior class="([^"]+)"', text)
    return bool(m) and m.group(1) in CLASSES


def inline_includes(text, seen=()):
    def sub(m):
        path = m.group(1)
        if path in seen:
            return ""
        f = REPO / "gamecode/sdk/hoh2" / path
        if not f.is_file():
            sys.exit(f"missing include {path}")
        inc = COMMENT_RE.sub("", f.read_text(encoding="utf-8", errors="replace"))
        return inline_includes(inc, seen + (path,)).rstrip("\n") + "\n"
    return INCLUDE_RE.sub(sub, text)


def absolutize(text, rel):
    d = "actors/" + rel.rsplit("/", 1)[0] + "/" if "/" in rel else "actors/"
    return text.replace('="./', '="' + d)


def drop_bossbar(text):
    while True:
        a = text.find('<dict name="bossbar">')
        if a < 0:
            return text
        b = text.find("</dict>", a)
        start = text.rfind("\n", 0, a) + 1
        end = text.find("\n", b) + 1
        text = text[:start] + text[end:]


def clamp_circles(text):
    def sub(m):
        tag = m.group(0)
        if 'sensor="true"' in tag:
            return tag
        return re.sub(r'radius="(\d+(?:\.\d+)?)"', lambda r: f'radius="{min(float(r.group(1)), RADIUS_MAX):g}"', tag)
    return CIRCLE_RE.sub(sub, text)


PLAYER_TARGET_RE = re.compile(r"<(s|string)>tag</(?:s|string)>\s*<(?:s|string)>has</(?:s|string)>\s*<a>\s*<(?:s|string)>player</(?:s|string)>\s*</a>")
# a boss skill's `flag is <arena flag>` conditional line (CondFlag on the floor's flags, which the
# arena's script sets: boss_skills by the Face's fight, totem_skills by the totem poles', room_4 by
# the Bandit King's last room). Its own line in every boss file; a `<a>...</a>` transition is not matched.
ARENA_FLAG_RE = re.compile(r"^[ \t]*<(?:s|string)>flag</(?:s|string)>\s*<(?:s|string)>is</(?:s|string)>\s*"
                           r"<(?:s|string)>(?:boss_skills|totem_skills|room_4)</(?:s|string)>[ \t]*\r?\n", re.M)


def tags_of(text):
    m = TAGS_RE.search(text)
    return re.findall(r"<(?:string|s)>([^<]+)</(?:string|s)>", m.group(0)) if m else []


def common(rel, text):
    """the enemy's text made loadable from the mod's folder"""
    text = absolutize(inline_includes(text), rel)
    return GENERATED.format(rel=rel) + "\n" + text


def risen_unit(rel, text):
    tags = tags_of(text)
    text = common(rel, text)
    cls = re.search(r'<behavior class="([^"]+)"', text).group(1)
    text = text.replace(f'<behavior class="{cls}"', f'<behavior class="{CLASSES[cls]}"', 1)
    text = TEAM_RE.sub('<string name="team">player</string>', text)
    for name in DROP_PARAMS:
        text = re.sub(r'^[ \t]*<\w+ name="' + name + r'">[^\n]*</\w+>[ \t]*\r?\n', "", text, flags=re.M)
    text = drop_bossbar(text)
    text = text.replace('<string name="team">player</string>\n', '<string name="team">player</string>\n' + LEASHES, 1)

    def tags_sub(m):
        block = m.group(0)
        if "enemy" in tags:
            block = re.sub(r"<(string|s)>enemy</(?:string|s)>", r"<\1>summon</\1><\1>hwp_risen</\1>", block, count=1)
        else:
            block = block.replace("</array>", "<string>summon</string><string>hwp_risen</string></array>", 1)
        return block
    if TAGS_RE.search(text):
        text = TAGS_RE.sub(tags_sub, text, count=1)
    else:
        text = text.replace(LEASHES, LEASHES + '\t\t<array name="tags"><string>summon</string><string>hwp_risen</string></array>\n', 1)
    if rel in BOSS_HP:
        text = re.sub(r'<int name="hp">\d+</int>', f'<int name="hp">{BOSS_HP[rel]}</int>', text, count=1)
    # 31 attack skills in 15 units (the Face's spews, the Bandit King's, the Judges', the Spider
    # Queen's, the necromancers' ...) demand a player-tagged target, which a risen's enemy targets
    # never are: they aim at anything that isn't a player instead (bosses 20261022-052506: the
    # risen Face kept its target and never attacked). The two effect-level `conditional`s with the
    # same check (Dace Arden's chain link, the Spider Queen's spew_web, both `cond-target-self`
    # false: tested on the unit the effect hits) flip too, so the risen's link and web take the
    # non-players they hit; a skill-level `conditional` never asks this of the caster itself.
    text = PLAYER_TARGET_RE.sub(lambda mm: "<{0}>tag</{0}><{0}>hasnt</{0}><a><{0}>player</{0}></a>".format(mm.group(1)), text)
    # the arena flags go: a risen fights wherever its owner is, with no arena script to set them.
    # The boss's own phase flags (stage2, boss_dead ...) stay: its kept SetFlag effects set them.
    text = ARENA_FLAG_RE.sub("", text)
    if '<array name="movements">' not in text and IMMOBILE_RE.search(text):
        text = MIN_RANGE_RE.sub("", text)
    return clamp_circles(text)


def body_unit(rel, text):
    tags = tags_of(text)
    idle = re.search(r'<string name="anim-idle">([^<]+)</string>', text)
    text = common(rel, text)
    a = text.find("<behavior ")
    b = text.find("</behavior>", a) + len("</behavior>")
    behavior = ('<behavior class="HWPSpecsBody">\n'
                f'\t\t<string name="source">players/hwp/specs/forgemaster/risen/{rel}</string>\n'
                f'\t\t<bool name="elite">{"true" if "elite" in tags else "false"}</bool>\n'
                f'\t\t<bool name="boss">{"true" if "boss" in tags else "false"}</bool>\n'
                f'\t\t<string name="idle">{idle.group(1) if idle else "idle"}</string>\n'
                '\t</behavior>')
    return text[:a] + behavior + text[b:]


def units_as(enemies, rels):
    lines = ["// GENERATED by tools/make_forgemaster_risen.py; do not edit.",
             "// ENEMY_UNITS: every actor on team enemy (a risen's SpawnUnit of one of these is dropped,",
             "// Forgemaster.as StripActions). RISEN_RELS: the raisable ones, under actors/, with a risen",
             "// and a body unit in players/hwp/specs/forgemaster/.",
             "namespace HWP", "{", "\tnamespace Specs", "\t{",
             "\t\tconst array<string> ENEMY_UNITS = {"]
    lines += [f'\t\t\t"actors/{rel}",' for rel, _ in enemies]
    lines += ["\t\t};", "", "\t\tconst array<string> RISEN_RELS = {"]
    lines += [f'\t\t\t"{rel}",' for rel in rels]
    lines += ["\t\t};", "\t}", "}", ""]
    return "\n".join(lines)


def ignore_text(current):
    block = "\n".join([IGNORE_BEGIN, "/players/hwp/specs/forgemaster/risen/", "/players/hwp/specs/forgemaster/bodies/", IGNORE_END])
    a, b = current.find(IGNORE_BEGIN), current.find(IGNORE_END)
    if a >= 0 and b > a:
        return current[:a] + block + current[b + len(IGNORE_END):]
    return current.rstrip("\n") + ("\n" if current.strip() else "") + block + "\n"


def build():
    """{path: text} of everything this tool writes"""
    enemies = enemy_units()
    out = {}
    rels = []
    for rel, text in enemies:
        if not raisable(rel, text):
            continue
        rels.append(rel)
        out[RISEN / rel] = risen_unit(rel, text)
        out[BODIES / rel] = body_unit(rel, text)
    out[UNITS_AS] = units_as(enemies, rels)
    out[GITIGNORE] = ignore_text(GITIGNORE.read_text(encoding="utf-8") if GITIGNORE.is_file() else "")
    return out, rels


def main(argv):
    if not ACTORS.is_dir():
        sys.exit("gamecode/sdk/hoh2/actors missing: run tools/bootstrap.py first")
    out, rels = build()
    if "--list" in argv:
        print("\n".join(rels))
        print(f"{len(rels)} raisable")
        return
    bad = [(p, why) for p, t in out.items() if p.suffix == ".unit" and (why := well_formed(t))]
    for p, why in bad:
        print("malformed:", p.relative_to(REPO).as_posix(), "|", why)
    if bad:
        sys.exit(f"{len(bad)} generated unit(s) would not parse; nothing written")
    if "--check" in argv:
        stale = [p for p, t in out.items() if not p.is_file() or p.read_text(encoding="utf-8") != t]
        extra = [p for d in (RISEN, BODIES) if d.is_dir() for p in d.rglob("*.unit") if p not in out]
        for p in stale + extra:
            print("stale:", p.relative_to(REPO).as_posix())
        if stale or extra:
            sys.exit(1)
        return
    for d in (RISEN, BODIES):
        if d.is_dir():
            for p in d.rglob("*.unit"):
                if p not in out:
                    p.unlink()
    for p, t in out.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.is_file() or p.read_text(encoding="utf-8") != t:
            p.write_text(t, encoding="utf-8", newline="\n")
    print(f"wrote {len(rels)} risen + {len(rels)} body units, {UNITS_AS.relative_to(REPO).as_posix()}")


if __name__ == "__main__":
    main(sys.argv[1:])
