"""make_forgemaster_risen.py - the Devil Forgemaster's risen summons and intact bodies (mods/specs).

For every raisable enemy unit under gamecode/sdk/hoh2/actors/ (team enemy; a CompositeActor,
StateActor or TransferDamage actor; not on the EXCLUDE list) two units are written into mods/specs:

  players/hwp/specs/forgemaster/risen/<rel>    the summon: the enemy's own file with its behavior
      class swapped for HWPSpecsRisenUnit / HWPSpecsRisenStateUnit (scripts/HWP/Specs/
      Forgemaster_Risen.as, the running subclasses of Forgemaster.as's HWPSpecsRisen /
      HWPSpecsRisenState), team player, the summon tags and leashes, a target search twice as
      often (target-find-cooldown-mul SEARCH_MUL), and no loot, experience, respawn or boss bar.
      It looks like a summon, not an enemy: the `npc` material (the green silhouette through
      walls the NPCs and the Priest's crusaders have, not the enemies' red), the `npc_normal`
      minimap dot, and an elite's ring from marker/ (below) in the summon HP bar's orange
      instead of the enemies' red. Bosses get the BOSS_HP table and every solid collision circle
      is clamped to RADIUS_MAX so the summon fits the hallways (there is no radius setter at
      runtime).
  players/hwp/specs/forgemaster/bodies/<rel>   the intact body: HWPSpecsBodyUnit (grey) with the
      enemy's scenes made dead (dead_scenes): every sprite frozen on its first frame, no effects,
      lights or particles (a Dark Citadel wisp is nothing but effects: its idle scene gets the
      DEAD_CORE sprite, a small still grey orb), no minimap dot or elite ring, the `npc-noxray`
      material (no silhouette through walls), and every collision shape shoot-, aim- and
      charge-through, so a body never stops the Priest's beam or a shot (the behavior turns the
      unit's collision off; the raycasts read the shapes' flags).
  players/hwp/specs/forgemaster/marker/        the elite ring in RING_COLOR (elite_marker.unit,
      elite_marker_14/16/20.effect, and elite_marker.png in the base sheet's layout) and
      dead_core.png (a still grey orb, CORE_SIZE px). The two PNGs are drawn with Pillow (a project
      dependency), not copied or recoloured from the base game, so the package ships no base-game
      art.

The enemy's `%include "actors/..."` lines are inlined, because the game resolves "./x" paths
against the unit being loaded (horde_soldier/horde_soldier.inc says ./horde_soldier/...), so a
copy in another folder needs them absolute: every ="./x" becomes ="actors/<unit dir>/x".
scripts/HWP/Specs/Forgemaster_Units.as gets the enemy unit set (a risen's SpawnUnit actions
that spawn one of these are dropped) and the raisable list.

The copies derive from the player's own install, so they are gitignored (a marked block in
mods/specs/.gitignore) and remade here, like tools/class_units.py's copies.

    python tools/make_forgemaster_risen.py          # write
    python tools/make_forgemaster_risen.py --check  # exit 1 when anything on disk differs
    python tools/make_forgemaster_risen.py --list   # the raisable units, write nothing
    python -m unittest tools.test_make_forgemaster_risen   # the unit texts' invariants
"""
