"""Generate the Dev Arena loadout presets (docs/devarena/SPEC.md: Presets; "Decided during build" 13).

One preset per vanilla subclass (24) and tier (early, mid, end) = 72, plus the named variants
in tools/devarena/presets_hand.json. Output: mods/devarena/tweak/hwp/devarena_presets.sval,
which the game reads at boot (mods/devarena/scripts/HWP/DevArena/Loadout.as).

A preset is a header (class, level, ilvl, quality) and rows in the fixture setup's shape,
[verb, args...], all strings:
    ["stat", "dex", "26"]                    attribute points placed
    ["skill", "<skill id>", "<picks>"]       SkillUp calls (a sub-skill id works too)
    ["combo", "<combo id>", "<picks>"]       SkillUp(id, combo = true)
    ["equip", "<base item id>"]              built at the header's ilvl and quality
    ["trinket", "<trinket id>"]              into the run's trinket inventory

    python tools/make_presets.py            # write the .sval
    python tools/make_presets.py --check    # exit 1 when the .sval is stale or a preset is invalid
    python tools/make_presets.py --list     # one line per preset
"""
from __future__ import annotations

import argparse
import re
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools"))
from tools.devarena import gamedata as gd  # noqa: E402
import hwr_archive  # noqa: E402

SCHEMA = 1
OUT = REPO / "mods" / "devarena" / "tweak" / "hwp" / "devarena_presets.sval"
HAND = REPO / "tools" / "devarena" / "presets_hand.json"
HEADER = ("<!-- Dev Arena loadout presets. GENERATED by tools/make_presets.py; edit\n"
          "     tools/devarena/presets_hand.json for named variants. -->\n")
# tier: (level, ilvl, quality, gear tier, trinkets)
TIERS = {"early": (5, 5, "common", 1, 2), "mid": (12, 12, "uncommon", 2, 4), "end": (20, 20, "rare", 3, 6)}
QUALITY_ORDER = ["common", "uncommon", "rare", "epic"]
WEAPON_SLOTS = {"mainhand", "twohand", "offhand"}
SLOT_OF = {"mainhand": "MainHand", "twohand": "MainHand", "offhand": "OffHand", "head": "Head",
           "chest": "Chest", "feet": "Feet", "hands": "Hands", "back": "Back"}


def tiered(item_id: str, tier: int) -> str | None:
    """The same item family at `tier`, or the nearest lower tier that exists."""
    its = gd.items()
    for t in range(tier, 0, -1):
        for old, new in ((f"_t1", f"_t{t}"), ("_01", f"_0{t}"), ("_1a", f"_{t}a")):
            if old in item_id:
                cand = item_id.replace(old, new)
                if cand in its:
                    return cand
    return item_id if item_id in its else None


def gear(cls: gd.PlayerClass, tier: int, ilvl: int) -> list[str]:
    p = cls.primary
    want = [tiered(g, tier) for g in cls.start_gear]
    want += [tiered(f"head_{p}_t1a", tier), tiered(f"hands_{p}_1a", tier)]
    if ilvl >= 10:
        want.append("back_2a")
    return [w for w in want if w]


ATTRS = ("str", "dex", "int", "foc", "vit")


def base_attrs(cls: gd.PlayerClass) -> dict[str, int]:
    """The class's base-<attr>, a subclass inheriting what it leaves out from its parent."""
    out: dict[str, int] = {}
    c = cls
    while c is not None:
        for a in ATTRS:
            if a not in out and "base-" + a in c.base:
                out[a] = int(c.base["base-" + a])
        c = gd.classes().get(c.parent) if c.parent else None
    return {a: out.get(a, 0) for a in ATTRS}


def item_req(item_id: str, ilvl: int) -> dict[str, int]:
    """What the item asks at `ilvl`: EquipmentReqDef.GetRequirements (Items/Equipment.as:44) lerps
    req-<attr> by (ilvl - 1) / 9, unclamped, so ilvl 20 asks well past the range's top."""
    it = gd.items()[item_id]
    t = (ilvl - 1) / 9.0
    return {a: int((1 - t) * it[f"req-{a}"][0] + t * it[f"req-{a}"][1] + 0.5) for a in ATTRS if it.get(f"req-{a}")}


def fit_gear(cls: gd.PlayerClass, want: list[str], tier: int, ilvl: int, pts: int) -> tuple[list[str], dict[str, int]]:
    """Gear the build can wear and the attribute points that make it wearable. An item whose
    requirements are unmet stays equipped but grants nothing, and its weapon skills stay blocked
    (PlayerRecord.as:1909, PlayerTargetingHelper CheckSkillBlocked), so requirements come before
    the free points. Weapons first, then the rest cheapest first; an item the budget can't cover
    drops a tier, then is left off (a weapon is never left off: validate() reports it). Gear rolls
    are ignored, so this is conservative."""
    base = base_attrs(cls)
    placed = {a: 0 for a in ATTRS}

    def cost(item_id: str) -> int:
        return sum(max(0, n - base[a] - placed[a]) for a, n in item_req(item_id, ilvl).items())

    def take(item_id: str) -> None:
        for a, n in item_req(item_id, ilvl).items():
            placed[a] = max(placed[a], n - base[a])

    chosen: dict[int, str] = {}
    weapons = [i for i, w in enumerate(want) if gd.items()[w]["slot"] in WEAPON_SLOTS]
    rest = sorted((i for i in range(len(want)) if i not in weapons), key=lambda i: cost(want[i]))
    for i in weapons + rest:
        must = i in weapons
        cands = [c for c in (tiered(want[i], t) for t in range(tier, 0, -1)) if c]
        choice = next((c for c in cands if cost(c) <= pts - sum(placed.values())), cands[-1] if must else None)
        if choice is not None:
            take(choice)
            chosen[i] = choice
    out = [chosen[i] for i in sorted(chosen)]
    return out, placed


def trinket_score(t: dict, tags: set[str], primary: str) -> int:
    text = json.dumps({k: v for k, v in t.items() if "modifier" in k})
    score = 0
    for tag in tags:
        if f'"{tag}"' in text and '"skill-tags"' in text:
            score += 3
    if (primary in ("str", "dex") and "attack-power" in text) or (primary == "int" and "spell-power" in text):
        score += 2
    if '"health"' in text or "ArmorAdd" in text:
        score += 1
    return score


def pick_trinkets(cls: gd.PlayerClass, quality: str, n: int) -> list[str]:
    top = QUALITY_ORDER.index(quality)
    tags = {t for s in cls.skills for t in s.tags} - {"spell", "passive"}
    pool = [t for t in gd.trinkets().values() if QUALITY_ORDER.index(t.get("quality", "common")) <= top]
    pool.sort(key=lambda t: (-trinket_score(t, tags, cls.primary), t["id"]))
    return [t["id"] for t in pool[:n]]


def skill_order(cls: gd.PlayerClass) -> list[gd.Skill]:
    """Subclass skills first (the last two in the class list), actives before passives."""
    own = [s for s in cls.skills if s.picks > 0]
    sub, base = own[-2:], own[:-2]
    key = lambda s: 0 if s.active else 1  # noqa: E731
    return sorted(sub, key=key) + sorted(base, key=key)


def spend(order: list[gd.Skill], budget: int, picked: dict[str, int]) -> int:
    """One level per skill per pass, in order, while anything is affordable. Returns stars left."""
    while True:
        took = False
        for s in order:
            n = picked.get(s.id, 0)
            if n < s.picks and s.cost(n) <= budget:
                budget -= s.cost(n)
                picked[s.id] = n + 1
                took = True
        if not took:
            return budget


def generate(cls: gd.PlayerClass, tier: str) -> dict:
    level, ilvl, quality, gt, ntr = TIERS[tier]
    budget = gd.stars_at(level)
    combos: dict[str, int] = {}
    if tier != "early":
        combos["combo_kills"] = 1
    if tier == "end":
        cid = "combo_bull_rage" if cls.primary in ("str", "dex") else "combo_clear_mind"
        combos[cid] = 1
        budget -= gd.combos()[cid].cost(0)
    picked: dict[str, int] = {}
    order = skill_order(cls)
    if tier == "end":
        lead = order[0]
        mod = next((m for m in lead.mods if m.picks > 0), None)
        if mod is not None and lead.start >= 1:
            picked[mod.id] = 1
            budget -= mod.cost(0)
    spend(order, budget, picked)
    pts = gd.stat_points_at(level)
    items, placed = fit_gear(cls, gear(cls, 1, ilvl), gt, ilvl, pts)
    free = max(0, pts - sum(placed.values()))
    prim = round(free * 2 / 3)
    placed[cls.primary] += prim
    placed["vit"] += free - prim
    rows = [["stat", a, str(placed[a])] for a in (cls.primary, *[x for x in ATTRS if x != cls.primary]) if placed[a]]
    rows += [["skill", s.id, str(picked[s.id])] for s in order if picked.get(s.id)]
    rows += [["skill", k, str(v)] for k, v in picked.items() if k not in {s.id for s in order}]
    rows += [["combo", k, str(v)] for k, v in combos.items()]
    rows += [["equip", g] for g in items]
    rows += [["trinket", t] for t in pick_trinkets(cls, quality, ntr)]
    return {"id": f"{cls.id}/{tier}", "class": cls.id, "tier": tier, "level": level, "ilvl": ilvl,
            "quality": quality, "note": f"generated {tier}: L{level}, t{gt} ilvl {ilvl} {quality}", "rows": rows}


def apply_variant(base: dict, v: dict) -> dict:
    """A hand variant: rows keyed by (verb, first arg) replace the base's; a picks or amount of
    "0" drops the row; `add` rows are appended."""
    out = {**base, "id": v["id"], "note": v.get("note", "variant of " + base["id"]), "tier": base["tier"]}
    rows = [list(r) for r in base["rows"]]
    for r in v.get("set", []):
        key = (r[0], r[1])
        hit = [i for i, x in enumerate(rows) if (x[0], x[1]) == key]
        if hit:
            rows[hit[0]] = list(r)
        else:
            rows.append(list(r))
    rows = [r for r in rows if not (r[0] in ("skill", "combo", "stat") and r[2] == "0")]
    drop = {tuple(d) for d in v.get("drop", [])}
    rows = [r for r in rows if (r[0], r[1]) not in drop]
    for k in ("level", "ilvl", "quality"):
        if k in v:
            out[k] = v[k]
    out["rows"] = rows + [list(r) for r in v.get("add", [])]
    return out


def all_presets() -> list[dict]:
    out = [generate(c, t) for c in sorted(gd.subclasses(), key=lambda c: c.id) for t in TIERS]
    by_id = {p["id"]: p for p in out}
    if HAND.exists():
        for v in json.loads(HAND.read_text(encoding="utf-8"))["variants"]:
            out.append(apply_variant(by_id[v["from"]], v))
    return out


def validate(p: dict) -> list[str]:
    """Headless checks: everything SkillUp, the attribute assigner and the equip path would refuse."""
    errs = []
    cls = gd.classes().get(p["class"])
    if cls is None or not cls.parent:
        return [f"{p['id']}: no vanilla subclass {p['class']!r}"]
    lvl = int(p["level"])
    if not 1 <= lvl <= 20:
        errs.append(f"level {lvl} outside 1..20")
    skills = {s.id: s for s in cls.skills}
    mods = {m.id: m for s in cls.skills for m in s.mods}
    stars = gd.stars_at(lvl)
    spent = stat = 0
    picked: dict[str, int] = {}
    combos: dict[str, int] = {}
    slots: dict[str, str] = {}
    have = base_attrs(cls)
    reported: set[str] = set()
    for r in p["rows"]:
        verb, args = r[0], r[1:]
        if verb == "stat":
            if args[0] not in ("str", "dex", "int", "foc", "vit"):
                errs.append(f"stat {args[0]!r}")
            stat += int(args[1])
            have[args[0]] = have.get(args[0], 0) + int(args[1])
        elif verb in ("skill", "combo"):
            s = (skills.get(args[0]) or mods.get(args[0])) if verb == "skill" else gd.combos().get(args[0])
            if s is None:
                errs.append(f"{verb} {args[0]!r} is not in {cls.id}")
                continue
            n = int(args[1])
            if not 1 <= n <= s.picks:
                errs.append(f"{verb} {args[0]} picks {n} outside 1..{s.picks}")
                continue
            spent += sum(s.cost(k) for k in range(n))
            (picked if verb == "skill" else combos)[s.id] = n
        elif verb == "equip":
            it = gd.items().get(args[0])
            if it is None:
                errs.append(f"equip {args[0]!r}: no base item")
                continue
            slot = SLOT_OF[it["slot"]]
            if slot in slots:
                errs.append(f"equip {args[0]}: {slot} already holds {slots[slot]}")
            slots[slot] = args[0]
            if it["slot"] == "twohand":
                slots["OffHand"] = args[0]
        elif verb == "trinket":
            if args[0] not in gd.trinkets():
                errs.append(f"trinket {args[0]!r}: unknown")
        else:
            errs.append(f"verb {verb!r}")
    for m, n in picked.items():
        if m in mods:
            par = skills[mods[m].parent]
            if par.start + picked.get(par.id, 0) < 1:
                errs.append(f"sub-skill {m} without its skill {par.id}")
            for b in mods[m].blockers:
                if picked.get(b):
                    errs.append(f"sub-skill {m} is blocked by {b}")
    for c in combos:
        for b in gd.combos()[c].blockers:
            if combos.get(b):
                errs.append(f"combo {c} is blocked by {b}")
    for item_id in slots.values():
        lack = [f"{a} {have.get(a, 0)}<{n}" for a, n in item_req(item_id, int(p["ilvl"])).items() if have.get(a, 0) < n]
        if lack and item_id not in reported:
            reported.add(item_id)
            weapon = gd.items()[item_id]["slot"] in WEAPON_SLOTS
            errs.append(f"equip {item_id}: unusable at ilvl {p['ilvl']} ({', '.join(lack)})"
                        + ("; its skills stay blocked" if weapon else "; grants nothing"))
    if spent > stars:
        errs.append(f"{spent} stars spent, {stars} at level {lvl}")
    if stat > gd.stat_points_at(lvl):
        errs.append(f"{stat} attribute points placed, {gd.stat_points_at(lvl)} at level {lvl}")
    if p.get("quality") not in QUALITY_ORDER:
        errs.append(f"quality {p.get('quality')!r}")
    return [f"{p['id']}: {e}" for e in errs]


def favorites(presets: list[dict]) -> list[str]:
    """The hand file's favorites that still name a preset (the Loadout tab's top row)."""
    ids = {p["id"] for p in presets}
    hand = json.loads(HAND.read_text(encoding="utf-8")) if HAND.exists() else {}
    return [f for f in hand.get("favorites", []) if f in ids]


def doc(presets: list[dict]) -> dict:
    return {"schema": SCHEMA, "presets": presets, "favorites": favorites(presets)}


KEYED = ("stat", "skill", "combo")


def diff_variant(base: dict, logged: dict) -> dict:
    """A variant the Loadout tab logged (the build's full rows) as hand-file set/drop/add rows
    against the preset it came from, so the hand file stays a readable list of differences."""
    v = {"id": logged["id"], "from": base["id"], "note": logged.get("note", "saved in the Loadout tab")}
    have = {(r[0], r[1]): r for r in base["rows"] if r[0] in KEYED}
    now = {(r[0], r[1]): r for r in logged["rows"] if r[0] in KEYED}
    sets = [list(r) for k, r in now.items() if have.get(k) != r]
    drops = [list(k) for k in have if k not in now]
    base_items = [tuple(r[:2]) for r in base["rows"] if r[0] not in KEYED]
    now_items = [tuple(r[:2]) for r in logged["rows"] if r[0] not in KEYED]
    drops += [list(k) for k in dict.fromkeys(base_items) if k not in now_items]
    adds = [list(k) for k in now_items if k not in base_items]
    for key, rows in (("set", sets), ("drop", drops), ("add", adds)):
        if rows:
            v[key] = rows
    if logged.get("level", base["level"]) != base["level"]:
        v["level"] = logged["level"]
    return v


def import_log(text: str) -> tuple[int, bool]:
    """Fold the Loadout tab's loadout-variant and loadout-favorites log lines into the hand file.
    Returns (variants added, favorites changed)."""
    hand = json.loads(HAND.read_text(encoding="utf-8")) if HAND.exists() else {"variants": []}
    by_id = {p["id"]: p for p in all_presets()}
    added, favs = 0, None
    for line in text.splitlines():
        m = re.search(r"\[HWP:devarena\] loadout-(variant|favorites) (.*)$", line)
        if not m:
            continue
        payload = json.loads(m.group(2))
        if m.group(1) == "favorites":
            favs = payload
            continue
        base = by_id.get(payload["from"])
        if base is None:
            continue
        vid, n = payload["id"], 1
        while vid in by_id:
            n += 1
            vid = f"{payload['from']}+e{n}"
        payload["id"] = vid
        v = diff_variant(base, payload)
        hand["variants"].append(v)
        by_id[vid] = apply_variant(base, v)
        added += 1
    changed = favs is not None and favs != hand.get("favorites", [])
    if changed:
        hand["favorites"] = favs
    if added or changed:
        HAND.write_text(json.dumps(hand, indent=1) + "\n", encoding="utf-8")
    return added, changed


def to_sval(presets: list[dict]) -> str:
    return HEADER + hwr_archive.svalue_to_xml(doc(presets)) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--import-log", type=Path, metavar="LOG",
                    help="fold the Loadout tab's saved variants and favorites from a game log into the hand file first")
    a = ap.parse_args(argv)
    if a.import_log:
        added, changed = import_log(a.import_log.read_text(encoding="utf-8", errors="replace"))
        print(f"imported {added} variants{', favorites' if changed else ''} into {HAND.relative_to(REPO)}")
    presets = all_presets()
    errs = [e for p in presets for e in validate(p)]
    for e in errs:
        print("INVALID", e)
    if a.list:
        for p in presets:
            sk = sum(1 for r in p["rows"] if r[0] == "skill")
            print(f"{p['id']:34} L{p['level']:<3} {sk} skills, {sum(1 for r in p['rows'] if r[0] == 'equip')} gear, "
                  f"{sum(1 for r in p['rows'] if r[0] == 'trinket')} trinkets")
    text = to_sval(presets)
    if a.check:
        stale = not a.out.exists() or a.out.read_text(encoding="utf-8") != text
        if stale:
            print(f"{a.out.relative_to(REPO)} is stale: run python tools/make_presets.py")
        print(f"{len(presets)} presets, {len(errs)} invalid")
        return 1 if errs or stale else 0
    if errs:
        return 1
    a.out.parent.mkdir(parents=True, exist_ok=True)
    if not a.out.exists() or a.out.read_text(encoding="utf-8") != text:
        a.out.write_text(text, encoding="utf-8")
        print(f"wrote {a.out.relative_to(REPO)}")
    print(f"{len(presets)} presets, all valid")
    return 0


if __name__ == "__main__":
    sys.exit(main())
