"""Write docs/generated/verbs.md: every `gl` verb the GameLab mods register (RegisterVerb calls), its
argument signature, and the comment block above the function that implements it.

    python tools/list_verbs.py          # rewrite docs/generated/verbs.md
    python tools/list_verbs.py --check  # exit 1 when docs/generated/verbs.md is stale
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "generated" / "verbs.md"
REG = re.compile(r'RegisterVerb\("([^"]+)",\s*"([^"]*)",\s*(?:GameLab::)?Verb\((?:\w+::)*(\w+)\)')


def comment_above(src: str, func: str) -> str:
    m = re.search(r"\n((?:[ \t]*//[^\n]*\n)+)(?:[ \t]*[^\n/][^\n]*;\n(?:[ \t]*\n)?)?[ \t]*void " + func + r"\(", src)
    if not m:
        return ""
    return " ".join(l.strip()[2:].strip() for l in m.group(1).splitlines())


def gamelab_mods() -> list:
    """mods/gamelab-*, and any other mod whose module.json says "gamelab": true (mods/devarena)."""
    mods = set((REPO / "mods").glob("gamelab-*"))
    for mj in (REPO / "mods").glob("*/module.json"):
        try:
            if json.loads(mj.read_text(encoding="utf-8")).get("gamelab"):
                mods.add(mj.parent)
        except ValueError:
            pass
    return sorted(mods)


def build() -> str:
    lines = ["# GameLab `gl` verbs", "",
             "Generated by `tools/list_verbs.py` from the `RegisterVerb` calls; do not edit by hand.",
             "Send one as `gl <id> <verb> args` (a `{\"do\": \"gl\", \"verb\": ...}` scenario step, or",
             "`Pilot.cmd` from a bot). Measurement-only verbs say so in their description.", ""]
    for mod in gamelab_mods():
        srcs = {f: f.read_text(encoding="utf-8") for f in sorted(mod.rglob("*.as"))}
        regs = [m for s in srcs.values() for m in REG.finditer(s)]
        if not regs:
            continue
        lines += [f"## {mod.name}", "", "| verb | args | what |", "|---|---|---|"]
        for name, args, func in (m.groups() for m in regs):
            doc = next((c for c in (comment_above(s, func) for s in srcs.values()) if c), "")
            a = f"`{args}`".replace("|", chr(92) + "|") if args else ""
            lines.append(f"| `{name}` | {a} | {doc.replace('|', '/')} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        print("docs/generated/verbs.md is stale" if stale else "docs/generated/verbs.md is current")
        sys.exit(1 if stale else 0)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}: {text.count(chr(10) + '| `')} verbs")
